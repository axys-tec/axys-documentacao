-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.empreendimentos (
    emp_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_tenant_uuid     UUID    NOT NULL,                  -- RAIZ de isolamento. [VALIDAR] sem FK física (hub é banco externo).
