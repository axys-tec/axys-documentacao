-- ============================================================
-- TABELA: ativo.ativos                    (contrato §8.2)
-- O objeto técnico real (obra/projeto/edificação/contrato).
-- Núcleo ao qual TUDO se conecta. Pertence a 0..1 empreendimento.
--
-- atv_tenant_uuid: SEMPRE preenchido. A Axys tem tenant próprio (role interna) —
--   modelos do "catálogo de ativos" são ativos desse tenant, não linhas órfãs.
-- atv_is_catalog_source: marca um ativo como FONTE do catálogo de ativos (modelo/
--   template que alimenta o gerador por drivers). Default FALSE. Um ativo comum
--   do tenant nasce FALSE; a Axys (ou futuramente o próprio tenant) marca TRUE
--   para reusá-lo como modelo. Decisão "árvore única": modelo = ativo, sem schema
--   espelhado nem duplicação de tabela.
-- Documentação do ativo (repo-paradigma): NÃO fica em JSONB de cabeçalho (lição do
--   Catálogo: ins_external_path virou dívida → migrou p/ registro catalogo.documentos).
--   Fica em TABELA dedicada ativo.ativo_diversidades_catalog (registro real, sem NULLs).
--   Ver §DOCUMENTOS / DIVERSIDADES adiante.
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ativos (
    atv_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atv_tenant_uuid     UUID    NOT NULL,                  -- RAIZ de isolamento (inclui o tenant interno da Axys). [VALIDAR] sem FK física.
    atv_emp_id          INTEGER,                           -- 0..1 empreendimento; NULL = obra avulsa
    atv_is_catalog_source BOOLEAN NOT NULL DEFAULT FALSE,  -- TRUE = modelo/fonte do catálogo de ativos (drivers)
    atv_codigo_interno  TEXT,
    atv_tipo            TEXT,                              -- vertical/natureza (obra, projeto, edificação, contrato…)
    atv_nome            TEXT    NOT NULL,
    atv_status          TEXT    NOT NULL DEFAULT 'RASCUNHO',-- rascunho/ativo/arquivado…
    atv_uf              CHAR(2),                           -- UF default (sobreposta no contexto de preço)
    atv_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atv_atualizado_em   TIMESTAMPTZ,
    atv_criado_por      TEXT,
    atv_atualizado_por  TEXT,

    CONSTRAINT fk_ativos_emp
        FOREIGN KEY (atv_emp_id)
        REFERENCES ativo.empreendimentos (emp_id)
        ON UPDATE CASCADE ON DELETE SET NULL,

    CONSTRAINT ck_ativos_nome_vazio
        CHECK (btrim(atv_nome) <> '')
);

CREATE INDEX ix_ativos_tenant
    ON ativo.ativos (atv_tenant_uuid);
CREATE INDEX ix_ativos_emp
    ON ativo.ativos (atv_emp_id);
-- localizar rapidamente os modelos/fontes do catálogo de ativos
CREATE INDEX ix_ativos_catalog_source
    ON ativo.ativos (atv_is_catalog_source)
    WHERE atv_is_catalog_source;


