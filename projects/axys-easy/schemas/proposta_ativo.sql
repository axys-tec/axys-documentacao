-- ============================================================
-- TABELA: ativo.ficha_atributos           (contrato §8.5)
-- Valores preenchidos por ativo. VALOR EM COLUNAS TIPADAS (indexável),
-- nunca tudo em JSON. Filtragem analítica = view pivotada (não EAV no OLTP).
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ficha_atributos (
    atr_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atr_ficha_id        INTEGER NOT NULL,
    atr_par_id          INTEGER NOT NULL,
    atr_valor_numero    NUMERIC(18,6),
    atr_valor_texto     TEXT,
    atr_valor_bool      BOOLEAN,
    atr_valor_data      DATE,
    atr_meta_json       JSONB,                             -- só o genuinamente livre (lista/payload de driver)
    atr_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atr_atualizado_em   TIMESTAMPTZ,
    atr_criado_por      TEXT,
    atr_atualizado_por  TEXT,

    CONSTRAINT fk_atr_ficha
        FOREIGN KEY (atr_ficha_id)
        REFERENCES ativo.ativo_ficha_tecnica (ficha_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_atr_par
        FOREIGN KEY (atr_par_id)
        REFERENCES ativo.ficha_parametros (par_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_atr_ficha_par
        UNIQUE (atr_ficha_id, atr_par_id),
    CONSTRAINT ck_atr_meta_obj
        CHECK (atr_meta_json IS NULL OR jsonb_typeof(atr_meta_json) = 'object')
);

CREATE INDEX ix_atr_ficha
    ON ativo.ficha_atributos (atr_ficha_id);
CREATE INDEX ix_atr_par
    ON ativo.ficha_atributos (atr_par_id);


-- ============================================================
-- TABELA: ativo.ativo_itens               (contrato §8.6)  ★ CORAÇÃO ★
-- Árvore canônica: parent_id + ordem ESPARSA + path. Numeração 1.2.3 é
-- RENDER, não dado. NÃO carrega tenant_uuid (deriva via ati_atv_id).
--
-- PREÇO NÃO É COLUNA AQUI. O item guarda o VÍNCULO (origem + cmp_id + qtd)
-- e a camada de AJUSTE reversível (ati_ajuste_json). Custo resolve ao vivo
-- contra a edição do contexto (orcamento_parametros). Sem ati_custo_base.
--
-- ati_cmp_origem: discriminador da FK polimórfica da composição.
--   CATALOGO → catalogo.composicoes | TENANT → tenant_catalogo.composicoes
--   | LOCAL → ativo.orcamento_composicoes (fork). FK resolvida pelo app, NÃO
--   pelo banco (polimórfica). NULL = linha estrutural sem composição.
--
-- Vínculo item↔driver: NÃO é coluna aqui (evita zilhão de NULLs). É a tabela-ponte
--   ativo.ativo_itens_drivers (N:N) — só existe linha quando o item TEM driver.
--   Ver §CATÁLOGO DE ATIVOS / DRIVERS adiante.
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ativo_itens (
    ati_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ati_atv_id          INTEGER NOT NULL,
    ati_parent_id       INTEGER,                           -- pai na árvore; NULL = raiz. PROFUNDIDADE vem daqui.
    ati_ordem           INTEGER NOT NULL,                  -- ordem ESPARSA entre irmãos (1000, 2000…)
    ati_path            TEXT    NOT NULL,                  -- "0001.0002.0001" — DERIVADO; p/ ORDER BY e descendência
    ati_tipo            TEXT    NOT NULL,                  -- GRUPO | SERVIÇO | SUBTOTAL | TEXTO | OBSERVAÇÃO…
    ati_descricao       TEXT,
    ati_cmp_origem      TEXT,                              -- 'CATALOGO' | 'TENANT' | 'LOCAL' | NULL
    ati_cmp_id          INTEGER,                           -- id da composição NA origem (FK polimórfica via app)
    ati_quantidade      NUMERIC(18,6),                     -- derivada da memória se houver; senão digitada
    ati_unidade         TEXT,
    ati_bdi_id          INTEGER,                           -- BDI da linha (FK ativo_bdi; NULL em título/não-precificável). FK via ALTER (ver §BDI)
    ati_ajuste_json     JSONB,                             -- camada de ajuste REVERSÍVEL sobre o preço resolvido (§10)
    ati_have_memory_calc BOOLEAN NOT NULL DEFAULT FALSE,   -- qtd vem de memória (true) ou digitação (false)
    ati_regras_json     JSONB,                             -- metadados por tipo de linha
    ati_meta_json       JSONB,
    ati_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ati_atualizado_em   TIMESTAMPTZ,
    ati_criado_por      TEXT,
    ati_atualizado_por  TEXT,

    CONSTRAINT fk_ati_atv
        FOREIGN KEY (ati_atv_id)
        REFERENCES ativo.ativos (atv_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ati_parent
        FOREIGN KEY (ati_parent_id)
        REFERENCES ativo.ativo_itens (ati_id)
        ON UPDATE CASCADE ON DELETE CASCADE,  -- deletar nó = deletar subárvore (primitiva "deletar")

    CONSTRAINT ck_ati_tipo
        CHECK (ati_tipo IN ('GRUPO', 'SERVIÇO', 'SUBTOTAL', 'TEXTO', 'OBSERVAÇÃO')),
    CONSTRAINT ck_ati_cmp_origem
        CHECK (ati_cmp_origem IS NULL OR ati_cmp_origem IN ('CATALOGO', 'TENANT', 'LOCAL')),
    -- coerência vínculo: origem e id andam juntos (ambos nulos ou ambos preenchidos)
    CONSTRAINT ck_ati_cmp_par
        CHECK ( (ati_cmp_origem IS NULL     AND ati_cmp_id IS NULL)
             OR (ati_cmp_origem IS NOT NULL AND ati_cmp_id IS NOT NULL) ),
    CONSTRAINT ck_ati_ajuste_obj
        CHECK (ati_ajuste_json IS NULL OR jsonb_typeof(ati_ajuste_json) = 'object'),
    -- não há dois irmãos com a mesma ordem sob o mesmo pai (no mesmo ativo)
    CONSTRAINT uq_ati_irmaos_ordem
        UNIQUE (ati_atv_id, ati_parent_id, ati_ordem)
);

-- leitura ordenada da árvore inteira de um ativo (ORDER BY ati_path)
CREATE INDEX ix_ati_atv_path
    ON ativo.ativo_itens (ati_atv_id, ati_path);
-- filhos diretos
CREATE INDEX ix_ati_parent
    ON ativo.ativo_itens (ati_parent_id);
-- descendência por prefixo de path (LIKE 'x.%')
CREATE INDEX ix_ati_atv_path_text
    ON ativo.ativo_itens (ati_atv_id, ati_path text_pattern_ops);


-- ============================================================
-- TABELA: ativo.orcamento_parametros      (contrato §8.7)
-- CONTEXTO de preço por fonte. ROTACIONÁVEL: trocar opa_edicao_id re-resolve
-- todo o orçamento sem tocar item algum.
-- LS saiu daqui → ativo.ativo_ls (ÚNICA por obra). BDI saiu daqui → ativo.ativo_bdi
--   (1+ por obra) + ati_bdi_id por linha. Decisão Renan 2026-06-14.
-- [VALIDAR] opa_modalidade (SD/CD) pode ser redundante com ativo_ls.als_tipo
--   (ONERADA/DESONERADA = obra-level); manter por ora, reavaliar na implementação.
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.orcamento_parametros (
    opa_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opa_atv_id          INTEGER NOT NULL,
    opa_fonte           TEXT    NOT NULL,                  -- SINAPI | CDHU | TENANT…
    opa_edicao_id       INTEGER,                           -- edição-base (catalogo.edicoes). NULL p/ fonte TENANT.
    opa_uf              CHAR(2) NOT NULL DEFAULT 'SP',
    opa_modalidade      TEXT    NOT NULL DEFAULT 'SD',      -- SD | CD | SE  [VALIDAR vs ativo_ls.als_tipo]
    opa_default         BOOLEAN NOT NULL DEFAULT FALSE,    -- contexto inicial herdado na criação
    opa_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    opa_atualizado_em   TIMESTAMPTZ,
    opa_criado_por      TEXT,
    opa_atualizado_por  TEXT,

    CONSTRAINT fk_opa_atv
        FOREIGN KEY (opa_atv_id)
        REFERENCES ativo.ativos (atv_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_opa_edicao
        FOREIGN KEY (opa_edicao_id)
        REFERENCES catalogo.edicoes (edi_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_opa_modalidade
        CHECK (opa_modalidade IN ('SD', 'CD', 'SE')),
    -- um contexto por (ativo, fonte)
    CONSTRAINT uq_opa_atv_fonte
        UNIQUE (opa_atv_id, opa_fonte)
);

-- no máximo UM contexto default por ativo
CREATE UNIQUE INDEX uq_opa_um_default
    ON ativo.orcamento_parametros (opa_atv_id)
    WHERE opa_default;

CREATE INDEX ix_opa_atv
    ON ativo.orcamento_parametros (opa_atv_id);


-- ============================================================
