--   • Nomes/prefixos do contrato: emp_ atv_ ficha_ par_ atr_ ati_ opa_ ocp_ oci_
--     oin_ oip_ mc_ mci_ mil_ rev_ evt_.
--   • ati_path = TEXT zero-padded ("0001.0002"); índice DERIVADO da árvore
--     (verdade = ati_parent_id + ati_ordem). ltree NÃO usado (extensão ausente).
--   • Preço RESOLVIDO, não persistido: ativo_itens NÃO tem custo. Base SE@edição
--     (catálogo) + LS/BDI do contexto (orcamento_parametros), lazy. Só a emissão
--     congela (ativo_revisoes.rev_snapshot_json).
--   • Isolamento: tenant_uuid nas RAÍZES (empreendimentos, ativos, tenant_catalogo.*);
--     folhas derivam por FK. tenant_uuid SEMPRE preenchido — a Axys tem tenant próprio
--     na app (role interna); modelos do "catálogo de ativos" usam o tenant da Axys.
--     RLS-política DIFERIDA (coluna entra agora; policy depois).
--   • Catálogo consumido COMO ESTÁ (composição é por edição → custo@edição já resolvível).
--   • "Catálogo de ativos" = ÁRVORE ÚNICA (decidido): o modelo é um ATIVO comum marcado
--     atv_is_catalog_source=TRUE (sem schema espelhado, sem duplicação). Drivers ligam-se
--     ao item via TABELA-PONTE ativo.ativo_itens_drivers (N:N) — sem coluna nula em massa.
--   • PKs GENERATED BY DEFAULT (não ALWAYS) → permitem reinsert com id original na
--     RECONSTRUÇÃO (offboarding/arquivamento por tenant). Ver §ARQUIVAMENTO no fim.
--
-- ⚠️ PONTOS A VALIDAR (marcados [VALIDAR] no corpo)
--   • tenant_uuid: Hub é banco SEPARADO (EASY_HUB_DB_URL) → SEM FK física a hub_tenant.
--   • Drivers: desenho fino da regra (drv_regra_json) a detalhar quando o gerador nascer;
--     tabelas criadas como reserva CONCRETA (a pedido), lean e flexíveis por JSONB.
--   • tenant_catalogo.*: espelha catalogo.* — validar colunas finas contra o schema.sql
--     do Catálogo na implementação (contrato §8.14).
--   • §ARQUIVAMENTO (schema arquivo): lifecycle de desconstrução/reconstrução por tenant —
--     possível mover p/ contrato próprio. Incluído aqui como proposta concreta.
--
-- PADRÃO DA CASA (igual ao schema.sql do Catálogo)
--   Prefixo de coluna = abreviatura da tabela; PK INTEGER GENERATED BY DEFAULT AS IDENTITY;
--   TIMESTAMPTZ; valores NUMERIC(14,4); coeficientes NUMERIC(14,10);
--   audit trail: _criado_em/_atualizado_em/_criado_por/_atualizado_por.
-- ============================================================


