--   ficha_parametros, que é vocabulário só-global.) [VALIDAR se tenant cria driver]
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.drivers (
    drv_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drv_tenant_uuid     UUID,                              -- NULL = global (Axys). [VALIDAR] sem FK física.
    drv_codigo          TEXT    NOT NULL,                  -- código estável do driver
    drv_nome            TEXT    NOT NULL,
