-- 4) FERIADOS — nasce vazia; nenhum código a lê ainda
-- ═══════════════════════════════════════════════════════════════════════════
-- UMA tabela para os três níveis, e não JSON pendurado no município: a pergunta é sempre
-- "quais feriados afetam a obra no município X em 2026?", e a resposta é nacional + estadual +
-- municipal. Numa tabela isso é UMA consulta. A chave do município é o `mun_id`, que já É o
-- código IBGE de 7 dígitos — e é por ele que a fonte externa consulta.
CREATE TABLE IF NOT EXISTS catalogo.feriados (
    fer_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fer_ano         SMALLINT NOT NULL,
    fer_data        DATE     NOT NULL,
    fer_nome        TEXT     NOT NULL,
    fer_abrangencia TEXT     NOT NULL,          -- NACIONAL | ESTADUAL | MUNICIPAL
    fer_uf          CHAR(2),                    -- NULL no nacional
    fer_mun_id      INTEGER REFERENCES catalogo.municipios (mun_id)
                    ON UPDATE CASCADE ON DELETE CASCADE,   -- NULL salvo no municipal
    fer_tipo        TEXT,                       -- FERIADO | FACULTATIVO — o facultativo não para a obra
    fer_fonte       TEXT     NOT NULL,          -- de onde veio (ex.: 'feriadosapi')
    fer_coletado_em DATE     NOT NULL DEFAULT CURRENT_DATE,
    fer_criado_em   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_fer_abrangencia CHECK (fer_abrangencia IN ('NACIONAL','ESTADUAL','MUNICIPAL')),
    -- o escopo e a chave andam juntos: nacional sem UF nem município, estadual com UF e sem
    -- município, municipal com os dois. Sem isto, uma linha mal carregada vira feriado de todo
    -- mundo — e feriado a mais encurta a obra de quem não o tem.
    CONSTRAINT ck_fer_escopo CHECK (
        (fer_abrangencia = 'NACIONAL'  AND fer_uf IS NULL     AND fer_mun_id IS NULL) OR
        (fer_abrangencia = 'ESTADUAL'  AND fer_uf IS NOT NULL AND fer_mun_id IS NULL) OR
        (fer_abrangencia = 'MUNICIPAL' AND fer_uf IS NOT NULL AND fer_mun_id IS NOT NULL)),
    CONSTRAINT uq_fer UNIQUE (fer_data, fer_abrangencia, fer_uf, fer_mun_id)
);

CREATE INDEX IF NOT EXISTS ix_fer_ano_abr ON catalogo.feriados (fer_ano, fer_abrangencia);
CREATE INDEX IF NOT EXISTS ix_fer_mun     ON catalogo.feriados (fer_mun_id, fer_ano);
CREATE INDEX IF NOT EXISTS ix_fer_uf      ON catalogo.feriados (fer_uf, fer_ano);
