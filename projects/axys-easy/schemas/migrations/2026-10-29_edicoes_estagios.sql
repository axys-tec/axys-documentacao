-- O QUE MUDA. O estado dos estágios saía de `edicoes.edi_estagios` (JSONB, só o último estado) mais
-- um checkpoint best-effort no R2 (`_state/estagios.json`). Passa a morar nesta tabela: uma linha
-- por EXECUÇÃO de estágio, com início, fim, resumo e causa do erro. `estagios.py` lê e escreve só
-- aqui a partir deste commit. A coluna `edi_estagios` fica de pé, sem uso, até a tabela ser
-- validada em prod; sai numa migration própria.
--
-- POR QUÊ. O motor de associação (estágio `associacoes`) precisa perguntar "há associação aberta
-- em alguma fonte?" entre edições, e de falha com causa e histórico confiável de tentativas.
--
-- CARGA INICIAL. Uma linha por (edição, estágio) a partir do JSONB, só para os estados explícitos
-- (rodando/ok/erro/pendente_user) — locked/pronto são derivados e não se guardam. O `resumo` do
-- detalhe vai para `ee_resumo`; o resto do detalhe (import_params do preparar, motivo) para
-- `ee_detalhe`. Em 29/10, dev e prod tinham as mesmas 62 edições com estagios preenchidos.
--
-- IDEMPOTENTE: CREATE ... IF NOT EXISTS; a carga só insere (edição, estágio) que ainda não tem linha.
--
--   psql "$EASY_DB_URL" -v ON_ERROR_STOP=1 -f docs/projects/axys-easy/schemas/migrations/2026-10-29_edicoes_estagios.sql

BEGIN;

CREATE TABLE IF NOT EXISTS catalogo.edicoes_estagios (
    ee_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ee_edi_id   INTEGER NOT NULL REFERENCES catalogo.edicoes(edi_id) ON DELETE CASCADE,
    ee_estagio  TEXT    NOT NULL,
    ee_estado   TEXT    NOT NULL,
    ee_job_id   TEXT,
    ee_resumo   TEXT,
    ee_erro     TEXT,
    ee_detalhe  JSONB,
    ee_por      TEXT,
    ee_inicio   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ee_fim      TIMESTAMPTZ,
    CONSTRAINT ck_ee_estagio CHECK (ee_estagio IN ('preparar','precos','dados','documentos','associacoes')),
    CONSTRAINT ck_ee_estado  CHECK (ee_estado  IN ('rodando','ok','erro','pendente_user','skip','reaberto'))
);
CREATE INDEX IF NOT EXISTS ix_ee_edi ON catalogo.edicoes_estagios (ee_edi_id, ee_estagio, ee_id DESC);

INSERT INTO catalogo.edicoes_estagios
       (ee_edi_id, ee_estagio, ee_estado, ee_job_id, ee_resumo, ee_erro, ee_detalhe, ee_por,
        ee_inicio, ee_fim)
SELECT e.edi_id, j.k, j.v->>'estado', j.v->>'job_id',
       j.v->'detalhe'->>'resumo',
       CASE WHEN j.v->>'estado' = 'erro' THEN j.v->'detalhe'->>'resumo' END,
       NULLIF((j.v->'detalhe') - 'resumo', '{}'::jsonb),
       j.v->'detalhe'->>'por',
       COALESCE((j.v->>'em')::timestamptz, e.edi_atualizado_em, CURRENT_TIMESTAMP),
       CASE WHEN j.v->>'estado' <> 'rodando'
            THEN COALESCE((j.v->>'em')::timestamptz, e.edi_atualizado_em, CURRENT_TIMESTAMP) END
  FROM catalogo.edicoes e
 CROSS JOIN LATERAL jsonb_each(e.edi_estagios) AS j(k, v)
 WHERE e.edi_estagios IS NOT NULL
   AND jsonb_typeof(j.v) = 'object'
   AND j.k IN ('preparar','precos','dados','documentos')
   AND j.v->>'estado' IN ('rodando','ok','erro','pendente_user')
   AND NOT EXISTS (SELECT 1 FROM catalogo.edicoes_estagios x
                    WHERE x.ee_edi_id = e.edi_id AND x.ee_estagio = j.k)
 ORDER BY e.edi_id, array_position(ARRAY['preparar','precos','dados','documentos'], j.k);

COMMIT;
