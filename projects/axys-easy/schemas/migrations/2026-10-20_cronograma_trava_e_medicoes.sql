BEGIN;

ALTER TABLE ativo.ativo_orcamento_cronograma
    ADD COLUMN IF NOT EXISTS cro_travado boolean DEFAULT false NOT NULL;

CREATE TABLE IF NOT EXISTS ativo.ativo_orcamento_cronograma_medicoes (
    cme_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cme_cro_id        integer NOT NULL,
    cme_prev_snapshot jsonb   NOT NULL,
    cme_medicoes      jsonb   NOT NULL,
    cme_criado_em     timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    cme_atualizado_em timestamp with time zone,
    cme_criado_por    text,
    cme_atualizado_por text
);

-- UMA simulação aplicada por cronograma: o "Aplicar" atualiza a linha em vez de empilhar histórico,
-- e é isso que faz o "voltar" devolver sempre ao estado do USUÁRIO, nunca a uma rodada anterior.
DO $$ BEGIN
    ALTER TABLE ativo.ativo_orcamento_cronograma_medicoes
        ADD CONSTRAINT uq_ao_cme_cro UNIQUE (cme_cro_id);
EXCEPTION WHEN duplicate_table OR duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    ALTER TABLE ativo.ativo_orcamento_cronograma_medicoes
        ADD CONSTRAINT fk_ao_cme_cro FOREIGN KEY (cme_cro_id)
        REFERENCES ativo.ativo_orcamento_cronograma (cro_id) ON UPDATE CASCADE ON DELETE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

COMMIT;

