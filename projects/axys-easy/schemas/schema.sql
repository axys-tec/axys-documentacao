    sd_aliases               TEXT[]  NOT NULL DEFAULT '{}',  -- sinônimos/curadoria (MVP vazio)
    sd_tokens                TEXT[]  NOT NULL DEFAULT '{}',  -- palavras normalizadas
    sd_search_vector         TSVECTOR,            -- to_tsvector('portuguese', unaccent(texto_busca))
    -- facetas de filtro (denormalização barata — NÃO é regra de negócio):
    sd_fte_id                INTEGER,
    sd_tipo                  TEXT,                -- ti_codigo (INS); NULL p/ CPU
    sd_unidade               TEXT,
    sd_is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    sd_source_hash           TEXT    NOT NULL,    -- md5 das fontes → detecta mudança
    sd_indexed_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

