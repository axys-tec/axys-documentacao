-- TABELA: catalogo.search_document   (prefixo sd_)   — decisão Renan 2026-06-11
-- ÍNDICE DE BUSCA TEXTUAL (1×1 por entidade ATIVA: insumo ou composição/CPU).
-- Contrato canônico: docs/.../contracts/catalogo/CATALOGO_SEARCH.md.
--
-- Doutrina: PostgreSQL é a FONTE DA VERDADE. Esta tabela é um ÍNDICE — duplica
-- só TEXTO PESQUISÁVEL + FACETAS de filtro; NUNCA preço, composição analítica,
-- coeficientes ou regra de negócio. A busca devolve CANDIDATOS (entity_type+id+
-- score); a app REIDRATA o dado oficial nas tabelas-fonte. Arquitetura preparada
-- p/ trocar o motor (Postgres→Elasticsearch/OpenSearch) mudando só o adapter —
-- o contrato (SearchService) e esta tabela não mudam.
--
-- Campos: sd_descricao_normalizada (unaccent+upper, p/ trigram), sd_texto_busca
-- (haystack: código+descrição+aliases), sd_search_vector (tsvector pt p/ full-text),
-- sd_aliases (sinônimos/curadoria; MVP vazio), sd_tokens (palavras normalizadas).
-- FACETAS: sd_fte_id, sd_tipo (ti_codigo p/ INS; NULL p/ CPU), sd_unidade,
-- sd_is_active. sd_source_hash detecta mudança (skip reindex / base do delta worker).
-- Mantida por SearchIndexer (rebuild/rebuild_all + upsert); reindex no CRUD e em
-- LOTE ao fim do import. (UF/preço NÃO entram aqui — são dimensão de exibição.)
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.search_document (
    sd_id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sd_entity_type           TEXT    NOT NULL,   -- 'INS' (insumo) | 'CPU' (composição)
    sd_entity_id             INTEGER NOT NULL,   -- ins_id | cmp_id (da linha vigente)
    sd_codigo                TEXT    NOT NULL,
    sd_descricao_original    TEXT    NOT NULL,
    sd_descricao_normalizada TEXT    NOT NULL,   -- upper(unaccent(descricao)) — p/ pg_trgm
    sd_texto_busca           TEXT    NOT NULL,   -- haystack: codigo + descricao + aliases
    sd_aliases               TEXT[]  NOT NULL DEFAULT '{}',  -- sinônimos/curadoria (MVP vazio)
    sd_tokens                TEXT[]  NOT NULL DEFAULT '{}',  -- palavras normalizadas
    sd_search_vector         TSVECTOR,            -- to_tsvector('portuguese', unaccent(texto_busca))
    -- facetas de filtro (denormalização barata — NÃO é regra de negócio):
    sd_fte_id                INTEGER,
    sd_tipo                  TEXT,                -- ti_codigo (INS); NULL p/ CPU
    sd_unidade               TEXT,
    sd_is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    sd_source_hash           TEXT    NOT NULL,    -- md5 das fontes → detecta mudança
    sd_indexed_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_search_document_entity CHECK (sd_entity_type IN ('INS', 'CPU')),
    CONSTRAINT uq_search_document_entity UNIQUE (sd_entity_type, sd_entity_id)
);

CREATE INDEX IF NOT EXISTS ix_search_document_vector
    ON catalogo.search_document USING GIN (sd_search_vector);
CREATE INDEX IF NOT EXISTS ix_search_document_norm_trgm
    ON catalogo.search_document USING GIN (sd_descricao_normalizada catalogo.gin_trgm_ops);
CREATE INDEX IF NOT EXISTS ix_search_document_texto_trgm
