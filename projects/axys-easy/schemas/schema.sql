    fet_codigo          TEXT    NOT NULL,                  -- slug estável (INST_HIDRAULICAS…)
    fet_nome            TEXT    NOT NULL,                  -- rótulo exibido (CAIXA ALTA)
    fet_ordem           INTEGER NOT NULL,                  -- sequência construtiva (0,10,20…)
    fet_is_etapa_obra   BOOLEAN NOT NULL DEFAULT TRUE,     -- FALSE = conceitual (guarda-chuva)
    fet_parent_id       INTEGER,                           -- SUB-ETAPA: etapa-grupo pai (NULL = grupo de topo = Nível 1 do orçamento; filha = Nível 2)
    fet_ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    fet_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fet_atualizado_em   TIMESTAMPTZ,
    fet_criado_por      TEXT,
    fet_atualizado_por  TEXT,

    CONSTRAINT uq_fet_codigo UNIQUE (fet_codigo),
    CONSTRAINT fk_fet_parent
        FOREIGN KEY (fet_parent_id) REFERENCES ativo.ficha_tec_etapas (fet_id)
        ON UPDATE CASCADE ON DELETE CASCADE,               -- sub-etapa some com o grupo
    CONSTRAINT ck_fet_codigo_vazio CHECK (btrim(fet_codigo) <> ''),
    CONSTRAINT ck_fet_nome_vazio CHECK (btrim(fet_nome) <> '')
);

CREATE INDEX ix_fet_ordem ON ativo.ficha_tec_etapas (fet_ordem);
CREATE INDEX ix_fet_parent ON ativo.ficha_tec_etapas (fet_parent_id);


-- ============================================================
-- 4) ativo.ficha_tec_parametros  (VOCABULÁRIO de parâmetros)
-- fparam_etapa_id = FK NOT NULL p/ etapa. fparam_tipo = tipo do VALOR.
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ficha_tec_parametros (
    fparam_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fparam_etapa_id     INTEGER NOT NULL,
    fparam_codigo       TEXT    NOT NULL,
    fparam_descricao    TEXT    NOT NULL,
    fparam_tipo         TEXT    NOT NULL,                  -- NUMERO | TEXTO | BOOL | DATA | LISTA
    fparam_unidade      TEXT,
    fparam_ordem        INTEGER NOT NULL DEFAULT 1000,
    fparam_is_descritivel BOOLEAN NOT NULL DEFAULT FALSE,
    fparam_parent_id    INTEGER,                             -- CASCATA: parâmetro PAI (NULL = topo). Quais opções do pai abrem este filho ficam em ficha_tec_param_gatilho; SEM gatilho = qualquer valor do pai abre.
    fparam_ativo        BOOLEAN NOT NULL DEFAULT TRUE,
    fparam_criado_em    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fparam_atualizado_em TIMESTAMPTZ,
    fparam_criado_por   TEXT,
    fparam_atualizado_por TEXT,

    CONSTRAINT fk_fparam_etapa
        FOREIGN KEY (fparam_etapa_id)
        REFERENCES ativo.ficha_tec_etapas (fet_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_fparam_codigo UNIQUE (fparam_codigo),
    CONSTRAINT fk_fparam_parent
        FOREIGN KEY (fparam_parent_id)
        REFERENCES ativo.ficha_tec_parametros (fparam_id)
        ON UPDATE CASCADE ON DELETE CASCADE,                 -- cascata auto-referente (filho some com o pai)
    CONSTRAINT ck_fparam_tipo
        CHECK (fparam_tipo IN ('NUMERO', 'TEXTO', 'BOOL', 'DATA', 'LISTA')),
    CONSTRAINT ck_fparam_codigo_vazio CHECK (btrim(fparam_codigo) <> '')
);

CREATE INDEX ix_fparam_etapa ON ativo.ficha_tec_parametros (fparam_etapa_id, fparam_ordem);


-- ============================================================
-- 5) ativo.ficha_tec_param_opcoes   ★ NOVO ★  (opções controladas de LISTA)
-- Para parâmetros fparam_tipo = 'LISTA' (TIPO_ESTRUTURA = madeira/metal/concreto…).
-- Tira o valor-livre: a opção vira registro. uq (fpo_id, fpo_fparam_id) habilita a
-- FK COMPOSTA dos atributos (garante que a opção escolhida pertence ao parâmetro).
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ficha_tec_param_opcoes (
    fpo_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fpo_fparam_id       INTEGER NOT NULL,                  -- de qual parâmetro LISTA
    fpo_codigo          TEXT    NOT NULL,                  -- slug estável (MADEIRA, METALICA…)
    fpo_rotulo          TEXT    NOT NULL,                  -- exibido (Madeira, Metálica…)
    fpo_ordem           INTEGER NOT NULL DEFAULT 1000,
    fpo_ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    fpo_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fpo_atualizado_em   TIMESTAMPTZ,
    fpo_criado_por      TEXT,
    fpo_atualizado_por  TEXT,

    CONSTRAINT fk_fpo_fparam
        FOREIGN KEY (fpo_fparam_id)
        REFERENCES ativo.ficha_tec_parametros (fparam_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_fpo_param_codigo UNIQUE (fpo_fparam_id, fpo_codigo),
    -- alvo da FK composta dos atributos (a opção carrega o param a que pertence)
    CONSTRAINT uq_fpo_id_param UNIQUE (fpo_id, fpo_fparam_id),
    CONSTRAINT ck_fpo_codigo_vazio CHECK (btrim(fpo_codigo) <> '')
);

CREATE INDEX ix_fpo_fparam ON ativo.ficha_tec_param_opcoes (fpo_fparam_id, fpo_ordem);
CREATE INDEX ix_fparam_parent ON ativo.ficha_tec_parametros (fparam_parent_id);

-- ============================================================
-- 5-bis) ativo.ficha_tec_param_gatilho  — quais OPÇÕES do pai abrem um parâmetro-filho.
-- Filho aparece quando o valor escolhido no pai ∈ gatilhos. SEM gatilho = qualquer valor abre.
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ficha_tec_param_gatilho (
    fpg_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fpg_fparam_id       INTEGER NOT NULL,                  -- o parâmetro FILHO (condicional)
    fpg_fpo_id          INTEGER NOT NULL,                  -- a opção do PAI que o dispara
    CONSTRAINT fk_fpg_filho  FOREIGN KEY (fpg_fparam_id) REFERENCES ativo.ficha_tec_parametros (fparam_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_fpg_opcao  FOREIGN KEY (fpg_fpo_id)    REFERENCES ativo.ficha_tec_param_opcoes (fpo_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_fpg UNIQUE (fpg_fparam_id, fpg_fpo_id)
);
CREATE INDEX ix_fpg_filho ON ativo.ficha_tec_param_gatilho (fpg_fparam_id);


