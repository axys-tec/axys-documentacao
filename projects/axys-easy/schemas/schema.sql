-- TABELA: catalogo.edicoes_leis_sociais
-- Contrato de regra de negócio (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_BUSINESS_RULES.md  (§3.3 Leis sociais)
-- Leis sociais (encargos sobre MO) por edição / UF / modalidade — base da
-- derivação SD/CD: preco_modalidade = trunc(pelado*(1+LS/100), 2).
-- NÃO grava 'SE' (SE = 0% implícito). Fonte das LS: SINAPI = cabeçalhos das
--   abas ISD/ICD; CDHU = cabeçalho do arquivo de serviços (só horista).
-- els_horista / els_mensalista: percentual PUBLICADO (ex.: 115,54), dividido
--   por 100 no cálculo. Pelo menos um dos dois é obrigatório (CDHU = só horista).
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.edicoes_leis_sociais (
    els_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    els_edi_id         INTEGER NOT NULL,
    els_uf             CHAR(2) NOT NULL DEFAULT 'SP',
    els_modalidade     CHAR(2) NOT NULL,
    els_horista        NUMERIC(14,2),
    els_mensalista     NUMERIC(14,2),
    els_criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    els_atualizado_em  TIMESTAMPTZ,
    els_criado_por     TEXT,
    els_atualizado_por TEXT,

    CONSTRAINT fk_edicoes_leis_sociais_edi
        FOREIGN KEY (els_edi_id)
        REFERENCES catalogo.edicoes (edi_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT uq_edicoes_leis_sociais
        UNIQUE (els_edi_id, els_uf, els_modalidade),

    CONSTRAINT ck_edicoes_leis_sociais_modalidade
        CHECK (els_modalidade IN ('SD', 'CD')),

    CONSTRAINT ck_edicoes_leis_sociais_algum
        CHECK (els_horista IS NOT NULL OR els_mensalista IS NOT NULL)
);

CREATE INDEX ix_edicoes_leis_sociais_edi
    ON catalogo.edicoes_leis_sociais (els_edi_id);

