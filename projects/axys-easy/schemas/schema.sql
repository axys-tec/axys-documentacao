    mc_origem           TEXT    NOT NULL,                  -- VIA PLUGIN/API: 'CAD'|'RVT'|'IFC' | DIGITADA: 'MANUAL'. platform fica no json_cru (axysCAD §1.2)
    mc_arquivo          TEXT,                              -- source.file_name (plugin); NULL no MANUAL
    mc_hash             TEXT,                              -- checksum p/ provenance (plugin); NULL no MANUAL
    mc_json_cru         JSONB,                             -- payload axys-cad-v1 bruto = verdade (plugin). NULL no MANUAL (verdade = mc_corpo + os memo_calc_item)
    -- MANUAL (grid mini-excel) — título + corpo (células por id estável) + dimensões.
    mc_titulo           TEXT    NOT NULL DEFAULT 'Memória de cálculo',
    mc_corpo            JSONB   NOT NULL DEFAULT '{"celulas":{},"prox_id":1}'::jsonb,
    mc_qtd_colunas      SMALLINT DEFAULT 11,               -- A–K (sem coluna-margem)
    mc_qtd_linhas       SMALLINT DEFAULT 10,               -- começa em 10; UI estende ("+ linha" / inserir acima-abaixo)
    mc_versao           INTEGER NOT NULL DEFAULT 1,        -- etag (concorrência otimista)
    mc_importado_em     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mc_importado_por    TEXT,
    mc_atualizado_em    TIMESTAMPTZ,
    mc_atualizado_por   TEXT,

