-- ============================================================
-- 8) ativo.ativo_ficha_tec_atributos  (VALOR por ativo)
-- Valor em coluna tipada conforme fparam_tipo:
--   NUMERO→numero · TEXTO→texto · BOOL→bool · DATA→data · LISTA→opcao_id (FK).
-- fatr_valor_opcao_id: FK COMPOSTA (fparam_id, opcao_id) → garante que a opção
--   pertence ao parâmetro. NULL p/ tipos não-LISTA (FK composta MATCH SIMPLE
--   só valida quando ambas as colunas estão preenchidas).
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ativo_ficha_tec_atributos (
    fatr_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fatr_atv_id         INTEGER NOT NULL,
    fatr_fparam_id      INTEGER NOT NULL,
    fatr_valor_numero   NUMERIC(18,6),
    fatr_valor_texto    TEXT,
    fatr_valor_bool     BOOLEAN,
    fatr_valor_data     DATE,
    fatr_valor_opcao_id INTEGER,                           -- LISTA: FK p/ ficha_tec_param_opcoes (composta)
    fatr_criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fatr_atualizado_em  TIMESTAMPTZ,
    fatr_criado_por     TEXT,
    fatr_atualizado_por TEXT,

    CONSTRAINT fk_fatr_atv
        FOREIGN KEY (fatr_atv_id) REFERENCES ativo.ativos (atv_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_fatr_fparam
        FOREIGN KEY (fatr_fparam_id) REFERENCES ativo.ficha_tec_parametros (fparam_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- integridade real: a opção escolhida TEM de pertencer ao parâmetro do atributo
    CONSTRAINT fk_fatr_opcao
        FOREIGN KEY (fatr_fparam_id, fatr_valor_opcao_id)
        REFERENCES ativo.ficha_tec_param_opcoes (fpo_fparam_id, fpo_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_fatr_atv_fparam UNIQUE (fatr_atv_id, fatr_fparam_id)
);

CREATE INDEX ix_fatr_atv    ON ativo.ativo_ficha_tec_atributos (fatr_atv_id);
CREATE INDEX ix_fatr_fparam ON ativo.ativo_ficha_tec_atributos (fatr_fparam_id);
CREATE INDEX ix_fatr_opcao  ON ativo.ativo_ficha_tec_atributos (fatr_valor_opcao_id)
    WHERE fatr_valor_opcao_id IS NOT NULL;


-- ============================================================
-- 9) SEED — FICHA TÉCNICA (gerado do estado curado; idempotente via helpers pg_temp).
--    Etapa-árvore (fet_parent_id) → params (fparam_parent_id + gatilhos) → opções + DECK.
-- ============================================================
CREATE OR REPLACE FUNCTION pg_temp.grp(p_cod text,p_nome text,p_ord int,p_obra boolean) RETURNS void LANGUAGE sql AS $$
  INSERT INTO ativo.ficha_tec_etapas (fet_codigo,fet_nome,fet_ordem,fet_is_etapa_obra,fet_parent_id) VALUES (p_cod,p_nome,p_ord,p_obra,NULL)
  ON CONFLICT (fet_codigo) DO UPDATE SET fet_nome=EXCLUDED.fet_nome,fet_ordem=EXCLUDED.fet_ordem,fet_is_etapa_obra=EXCLUDED.fet_is_etapa_obra,fet_parent_id=NULL; $$;
CREATE OR REPLACE FUNCTION pg_temp.sub(p_parent text,p_cod text,p_nome text,p_ord int) RETURNS void LANGUAGE sql AS $$
  INSERT INTO ativo.ficha_tec_etapas (fet_codigo,fet_nome,fet_ordem,fet_is_etapa_obra,fet_parent_id)
  SELECT p_cod,p_nome,p_ord,TRUE,(SELECT fet_id FROM ativo.ficha_tec_etapas WHERE fet_codigo=p_parent)
  ON CONFLICT (fet_codigo) DO UPDATE SET fet_nome=EXCLUDED.fet_nome,fet_ordem=EXCLUDED.fet_ordem,fet_parent_id=EXCLUDED.fet_parent_id; $$;
CREATE OR REPLACE FUNCTION pg_temp.par(p_etapa text,p_cod text,p_descr text,p_tipo text,p_unid text,p_ord int,p_parent text) RETURNS void LANGUAGE sql AS $$
  INSERT INTO ativo.ficha_tec_parametros (fparam_etapa_id,fparam_codigo,fparam_descricao,fparam_tipo,fparam_unidade,fparam_ordem,fparam_is_descritivel,fparam_parent_id)
  SELECT e.fet_id,p_cod,p_descr,p_tipo,NULLIF(p_unid,''),p_ord,FALSE,(SELECT fparam_id FROM ativo.ficha_tec_parametros WHERE fparam_codigo=p_parent)
  FROM ativo.ficha_tec_etapas e WHERE e.fet_codigo=p_etapa
  ON CONFLICT (fparam_codigo) DO UPDATE SET fparam_etapa_id=EXCLUDED.fparam_etapa_id,fparam_descricao=EXCLUDED.fparam_descricao,fparam_tipo=EXCLUDED.fparam_tipo,fparam_unidade=EXCLUDED.fparam_unidade,fparam_ordem=EXCLUDED.fparam_ordem,fparam_parent_id=EXCLUDED.fparam_parent_id; $$;
CREATE OR REPLACE FUNCTION pg_temp.opt(p_param text,p_cod text,p_rot text,p_ord int) RETURNS void LANGUAGE sql AS $$
  INSERT INTO ativo.ficha_tec_param_opcoes (fpo_fparam_id,fpo_codigo,fpo_rotulo,fpo_ordem)
  SELECT fparam_id,p_cod,p_rot,p_ord FROM ativo.ficha_tec_parametros WHERE fparam_codigo=p_param
  ON CONFLICT (fpo_fparam_id,fpo_codigo) DO UPDATE SET fpo_rotulo=EXCLUDED.fpo_rotulo,fpo_ordem=EXCLUDED.fpo_ordem; $$;
CREATE OR REPLACE FUNCTION pg_temp.gat(p_child text,p_parent text,p_opt text) RETURNS void LANGUAGE sql AS $$
  INSERT INTO ativo.ficha_tec_param_gatilho (fpg_fparam_id,fpg_fpo_id)
  SELECT c.fparam_id,o.fpo_id FROM ativo.ficha_tec_parametros c JOIN ativo.ficha_tec_parametros pp ON pp.fparam_codigo=p_parent
  JOIN ativo.ficha_tec_param_opcoes o ON o.fpo_fparam_id=pp.fparam_id AND o.fpo_codigo=p_opt WHERE c.fparam_codigo=p_child ON CONFLICT DO NOTHING; $$;

