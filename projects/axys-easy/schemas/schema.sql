-- TABELA: catalogo.composicoes_itens
-- Contrato de regra de negócio (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_BUSINESS_RULES.md  (§4-§5)
-- Itens de cada composição na sua edição.
-- Filho pode ser insumo ('INSUMO') ou sub-composição ('COMPOSICAO').
-- Vinculado à composição versionada (cmp_id inclui edição).
-- Ciclos proibidos — verificados na camada de aplicação.
--
-- ci_situacao: situação do item na fonte — 'COM PREÇO' | 'SEM PREÇO'
--   | 'COM CUSTO' | 'SEM CUSTO' | 'SUSPENSO' | 'EM ESTUDO'.
-- ci_codigo/descricao/unidade_fonte_original: texto BRUTO da fonte,
--   preservado para auditoria/conferência/debug de parser, mesmo após
--   o item ser resolvido para FK (ci_ins_id / ci_cmp_filho_id).
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.composicoes_itens (
    ci_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci_cmp_id          BIGINT       NOT NULL,
    ci_tipo_filho      TEXT          NOT NULL,
    ci_ins_id          BIGINT,
    ci_cmp_filho_id    BIGINT,
    ci_coef            NUMERIC(14,10) NOT NULL,
    ci_situacao        TEXT,
    ci_codigo_fonte_original     TEXT,
    ci_descricao_fonte_original  TEXT,
    ci_unidade_fonte_original    TEXT,
    ci_ordem           SMALLINT      NOT NULL DEFAULT 0,
    ci_criado_em       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ci_atualizado_em   TIMESTAMPTZ,
    ci_criado_por      TEXT,
    ci_atualizado_por  TEXT,

    CONSTRAINT fk_ci_cmp
        FOREIGN KEY (ci_cmp_id)
        REFERENCES catalogo.composicoes (cmp_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_ci_ins
        FOREIGN KEY (ci_ins_id)
        REFERENCES catalogo.insumos (ins_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_ci_cmp_filho
        FOREIGN KEY (ci_cmp_filho_id)
        REFERENCES catalogo.composicoes (cmp_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT ck_ci_tipo_filho
        CHECK (ci_tipo_filho IN ('INSUMO', 'COMPOSICAO')),

    CONSTRAINT ck_ci_filho_xor
        CHECK (
            (ci_tipo_filho = 'INSUMO'
                AND ci_ins_id IS NOT NULL
                AND ci_cmp_filho_id IS NULL)
            OR
            (ci_tipo_filho = 'COMPOSICAO'
                AND ci_cmp_filho_id IS NOT NULL
                AND ci_ins_id IS NULL)
        ),

    -- Fidelidade à fonte: a CPU é gravada EXATAMENTE como a fonte apresenta.
    -- A SINAPI publica itens com coeficiente 0 (item presente na composição, com
    -- quantidade não atribuída / composição incompleta ou sem custo). Não cabe à
    -- app julgar o dado, só repeti-lo — por isso 0 é válido (≥ 0). Negativo segue
    -- barrado (não existe em SINAPI; seria lixo). Insumo SEM PREÇO com coef 0 ainda
    -- propaga sem-custo na árvore (a presença basta, não o coeficiente).
    CONSTRAINT ck_ci_coef_nao_negativo
        CHECK (ci_coef >= 0),

    CONSTRAINT ck_ci_situacao
        CHECK (
            ci_situacao IS NULL
            OR (ci_tipo_filho = 'INSUMO'
                AND ci_situacao IN ('COM PREÇO', 'SEM PREÇO'))
            OR (ci_tipo_filho = 'COMPOSICAO'
                AND ci_situacao IN ('COM CUSTO', 'SEM CUSTO', 'SUSPENSO', 'EM ESTUDO'))
        ),

    CONSTRAINT uq_ci_cmp_ins
        UNIQUE (ci_cmp_id, ci_ins_id),

    CONSTRAINT uq_ci_cmp_filho
        UNIQUE (ci_cmp_id, ci_cmp_filho_id)
);

CREATE INDEX ix_ci_cmp
    ON catalogo.composicoes_itens (ci_cmp_id, ci_ordem);

CREATE INDEX ix_ci_ins
    ON catalogo.composicoes_itens (ci_ins_id)
    WHERE ci_ins_id IS NOT NULL;

CREATE INDEX ix_ci_cmp_filho
    ON catalogo.composicoes_itens (ci_cmp_filho_id)
    WHERE ci_cmp_filho_id IS NOT NULL;


