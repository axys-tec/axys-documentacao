    mci_entidades_consideradas JSONB,                      -- entities[] — evidência (handle/type/layer/coords). Prova, não fonte.
    mci_status          TEXT    NOT NULL DEFAULT 'SYNCED', -- SYNCED | SUPERSEDED (re-levantamento preserva histórico — axysCAD §9)
