-- ============================================================
-- TABELA: catalogo.insumos_historico
-- Trilha de auditoria da EVOLUÇÃO CADASTRAL do insumo ao longo das
-- edições da fonte-base (criação, alteração de descrição/unidade/
-- tipo/classificação, inativação, reativação). Implementada na origem.
--
-- NÃO armazena preços e NÃO substitui catalogo.insumos_preco (série
-- histórica de preços por edição/UF/modalidade). catalogo.insumos
-- continua representando o ESTADO VIGENTE; esta tabela guarda o
-- histórico documental.
--
-- ih_tipo_evento: CRIACAO | ALTERACAO | INATIVACAO | REATIVACAO.
-- ih_edi_id_inicio / ih_edi_id_fim: faixa de edições (fim NULL = aberto).
-- JSONB intencional: o conjunto de campos alterados varia por
--   fonte-base/versão — snapshot/diff documental.
-- Append-only: sem _atualizado_* (snapshots imutáveis).
--
-- ESTRUTURA RECOMENDADA dos JSONB (NÃO contrato rígido — pode variar
--   conforme fonte-base, parser e tipo de alteração):
--   CRIACAO    → ih_dados_novos {edicao, codigo, descricao, unidade, tipo, ativo}
--   ALTERACAO  → ih_dados_anteriores {edicao_origem, descricao, unidade, tipo, ativo};
--                ih_dados_novos {edicao_alteracao, descricao, unidade, tipo, ativo};
--                ih_diff {descricao:{de,para}, unidade:{de,para}}  (só os mudados)
--   INATIVACAO → ih_dados_anteriores {ultima_edicao_ativa, codigo, ..., ativo:true};
--                ih_dados_novos {edicao_inativacao, ativo:false};
--                ih_diff {ativo:{de:true, para:false}}
--   REATIVACAO → simétrico (edicao_reativacao; ativo:{de:false, para:true})
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.insumos_historico (
    ih_id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ih_ins_id            BIGINT NOT NULL,
    ih_edi_id_inicio     INTEGER,
    ih_edi_id_fim        INTEGER,
    ih_tipo_evento       TEXT    NOT NULL,
    ih_dados_anteriores  JSONB,
    ih_dados_novos       JSONB,
    ih_diff              JSONB,
    ih_observacao        TEXT,
    ih_criado_em         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ih_criado_por        TEXT,

    CONSTRAINT fk_insumos_historico_ins
        FOREIGN KEY (ih_ins_id)
        REFERENCES catalogo.insumos (ins_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_insumos_historico_edi_inicio
        FOREIGN KEY (ih_edi_id_inicio)
        REFERENCES catalogo.edicoes (edi_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_insumos_historico_edi_fim
        FOREIGN KEY (ih_edi_id_fim)
        REFERENCES catalogo.edicoes (edi_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT ck_insumos_historico_tipo_evento
        CHECK (ih_tipo_evento IN
            ('CRIACAO', 'ALTERACAO', 'INATIVACAO', 'REATIVACAO'))
);

CREATE INDEX ix_insumos_historico_ins
    ON catalogo.insumos_historico (ih_ins_id);
CREATE INDEX ix_insumos_historico_ins_edi
    ON catalogo.insumos_historico (ih_ins_id, ih_edi_id_inicio);
CREATE INDEX ix_insumos_historico_tipo
    ON catalogo.insumos_historico (ih_tipo_evento);
CREATE INDEX ix_insumos_historico_diff
    ON catalogo.insumos_historico USING GIN (ih_diff);


