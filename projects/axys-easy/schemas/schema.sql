        CHECK (mc_origem IN ('CAD', 'RVT', 'IFC', 'MANUAL')),
    CONSTRAINT ck_mc_json_obj
        CHECK (mc_json_cru IS NULL OR jsonb_typeof(mc_json_cru) = 'object'),
    CONSTRAINT ck_mc_corpo_obj
        CHECK (jsonb_typeof(mc_corpo) = 'object'),
    -- plugin/API SEMPRE traz o payload bruto; MANUAL não tem payload (digitação é a verdade)
    CONSTRAINT ck_mc_json_por_origem
        CHECK (mc_origem = 'MANUAL' OR mc_json_cru IS NOT NULL),
    -- UPSERT idempotente por arquivo (axysCAD §9: reenviar o mesmo arquivo sobrescreve).
