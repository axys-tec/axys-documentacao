-- ============================================================
-- §CATÁLOGO DE ATIVOS / DRIVERS  (decisão 2026-06-14 — fora do contrato v0.2)
-- O gerador automatizado de orçamento é o produto vendável da Axys: a partir dos
-- PARÂMETROS da ficha (ficha_parametros/atributos) e de um MODELO (ativo com
-- atv_is_catalog_source=TRUE), DRIVERS calculam quantidades dos itens.
-- "Árvore única": o modelo é um ativo comum; gerar = copiar a subárvore do modelo
-- para o ativo do tenant + rodar os drivers contra a ficha dele.
--
-- drv_regra_json: [VALIDAR] formato da regra/fórmula (referencia par_codigo de
--   entrada → quantidade). Mantido JSONB p/ evoluir SEM ALTER (refator quase proibido).
-- drv_tenant_uuid NULL = driver GLOBAL (Axys, visível a todos); preenchido = driver
--   privado do tenant. (Driver É customizável por tenant — ao contrário de
--   ficha_parametros, que é vocabulário só-global.) [VALIDAR se tenant cria driver]
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.drivers (
    drv_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drv_tenant_uuid     UUID,                              -- NULL = global (Axys). [VALIDAR] sem FK física.
    drv_codigo          TEXT    NOT NULL,                  -- código estável do driver
    drv_nome            TEXT    NOT NULL,
    drv_descricao       TEXT,
    drv_tipo            TEXT,                              -- natureza da regra (FORMULA, LOOKUP…) — [VALIDAR]
    drv_unidade         TEXT,                              -- unidade da quantidade gerada
    drv_regra_json      JSONB,                             -- a regra/fórmula (entradas = par_codigo). [VALIDAR]
    drv_ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    drv_meta_json       JSONB,
    drv_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    drv_atualizado_em   TIMESTAMPTZ,
    drv_criado_por      TEXT,
    drv_atualizado_por  TEXT,

    CONSTRAINT uq_drivers_codigo_tenant
        UNIQUE (drv_tenant_uuid, drv_codigo),
    CONSTRAINT ck_drivers_regra_obj
        CHECK (drv_regra_json IS NULL OR jsonb_typeof(drv_regra_json) = 'object'),
    CONSTRAINT ck_drivers_meta_obj
        CHECK (drv_meta_json IS NULL OR jsonb_typeof(drv_meta_json) = 'object')
);

-- ------------------------------------------------------------
-- TABELA-PONTE: ativo.ativo_itens_drivers  (N:N item ↔ driver)
