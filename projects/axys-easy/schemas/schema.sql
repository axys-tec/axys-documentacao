-- ============================================================
-- AxysEasy — Schema SQL
-- Banco: PostgreSQL 14+
-- Schemas: catalogo · audit · ativo · tenant_catalogo · arquivo
--
-- catalogo   : catálogo de fontes de preços, insumos, preços por
--         edição/UF/modalidade, composições de preço versionadas
--         e hierarquia de grupos/subgrupos.
-- audit : trilha de auditoria — quem/quando/o quê/antes/depois.
-- ativo : módulo Ativo — orçamento (árvore), ficha, BDI/LS, cronograma,
--         memória de cálculo, revisões, drivers e diversidades. Ver bloco
--         "MÓDULO ATIVO" no fim deste arquivo.
-- tenant_catalogo : biblioteca técnica própria do tenant (insumos/composições).
-- arquivo : registro de desconstrução/reconstrução por tenant (offboarding).
--
-- Decisões de arquitetura
-- ───────────────────────
-- VERSIONAMENTO DE CATÁLOGO
--   composicoes, composicoes_itens, insumos_preco e composicoes_custo são
--   VERSIONADOS por edição (uma linha por edição, imutável — sem UPDATE/
--   DELETE em dados históricos). Re-importar a mesma edi_id é idempotente.
--   UNIQUE em composições: (cmp_fte_id, cmp_codigo, cmp_edi_id).
--   insumos é a IDENTIDADE VIGENTE por (fonte, código): pode ter atributos
--   cadastrais (descrição/unidade/tipo) atualizados a cada edição — o
--   histórico cadastral vai para catalogo.insumos_historico e a série de
--   preços é preservada por edição em insumos_preco.
--
-- UF / MODALIDADE
--   insumos_preco e composicoes_custo armazenam uma linha por
--   (insumo/composição, edição, uf, modalidade).
--   SINAPI: todas 27 UFs importadas por edição.
--   Estimativa: ~262 k linhas de preço de insumo por import (× 3 modalidades);
--   ~560 k de custo de composição (× 3 modalidades). PostgreSQL suporta com folga.
--   modalidade: 'SD' = sem desoneração | 'CD' = com desoneração | 'SE' = sem encargos sociais
--
-- TENANCY
--   Tabelas catalogo.*: catálogo compartilhado — sem tenant_uuid.
--   Dados do tenant (futuro módulo "ativo") carregarão tenant_uuid
--   quando implementados — fora deste schema por ora.
--
-- GRUPOS / SUBGRUPOS
--   catalogo.composicoes_grupos:    nível 1 (CDHU: código 'XX'; SINAPI: não usa)
--   catalogo.composicoes_subgrupos: nível 2 — sub_grp_id NULLABLE para SINAPI
--     (SINAPI usa sub_grp_id = NULL; seus "grupos" são subgrupos)
--
-- TIPO DE INSUMO
--   ins_tipo_sinapi: classificação exata da fonte (SINAPI verbatim
--     ou mapeado de outras fontes). Fidelidade ao dado original.
--   ins_ti_id: FK para catalogo.insumos_tipo
--     (MO / EQUIP_AQ / EQUIP_LOC / MAT / SERV / ESP)
--     agrupamento para histogramas e relatórios.
--   Mapeamento padrão SINAPI → insumos_tipo:
--     MATERIAL                → MAT
--     MAO DE OBRA             → MO
--     ENCARGOS COMPLEMENTARES → MO
--     EQUIPAMENTO (AQUISIÇÃO) → EQUIP_AQ
--     EQUIPAMENTO (LOCAÇÃO)   → EQUIP_LOC
--     SERVIÇOS                → SERV
--     ESPECIAIS               → ESP
--
-- PADRÃO DE NOMENCLATURA
--   Prefixo de coluna = abreviatura da tabela
--   PKs: INTEGER GENERATED BY DEFAULT AS IDENTITY
--   Timestamps: TIMESTAMPTZ; datas: DATE
--   Coeficientes: NUMERIC(14,10) (CDHU usa 4 casas, SINAPI 7); preços/valores: NUMERIC(14,4)
--   Audit trail: _criado_em, _atualizado_em, _criado_por, _atualizado_por
--
-- ESTRUTURA RECOMENDADA / CONTRATO INTERNO DA APP
-- Estes JSONB são gerados exclusivamente pela aplicação.
-- Não devem ser montados livremente por usuários, integrações externas
-- ou rotinas ad hoc.
-- A estrutura pode evoluir, mas somente por alteração deliberada da app,
-- com compatibilidade documentada e, quando necessário, versionamento.
-- Qualquer alteração estrutural nestes JSONB deve ser tratada como
-- mudança de contrato interno da aplicação.
--
-- DOCUMENTAÇÃO EXTERNA (JSONB) — ESTRUTURA CANÔNICA
--   Campos ativos: catalogo.insumos.ins_external_path e
--                  catalogo.composicoes.cmp_external_path.
--   O banco guarda só metadados/paths; o conteúdo fica no R2
--   (bucket easy-public). HTML é o documento principal; PDF é derivado;
--   assets ficam em pasta própria. tipo_documento varia por entidade:
--   'catalogo_tecnico' (insumo) | 'caderno_encargos' (composição); o
--   diretório segue /insumos/... ou /composicoes/...
--
--   {
--     "bucket": "easy-public",
--     "tipo_documento": "catalogo_tecnico",
--     "vigente": {
--       "revisao": "rev_001",
--       "edicao_inicio": "2024-10",
--       "edicao_fim": null,
--       "formato_principal": "html",
--       "html_path":   "/insumos/45087_2024-10_rev001.html",
--       "pdf_path":    "/insumos/45087_2024-10_rev001.pdf",
--       "assets_path": "/insumos/45087_2024-10_rev001_assets/",
--       "mime_type": "text/html",
--       "checksum": null,
--       "publicado_em": null,
--       "publicado_por": null,
--       "observacao": null
--     },
--     "revisoes": [
--       {
--         "revisao": "rev_001",
--         "edicao_inicio": "2024-10",
--         "edicao_fim": null,
--         "html_path":   "/insumos/45087_2024-10_rev001.html",
--         "pdf_path":    "/insumos/45087_2024-10_rev001.pdf",
--         "assets_path": "/insumos/45087_2024-10_rev001_assets/",
--         "status": "VIGENTE",
--         "publicado_em": null,
--         "publicado_por": null,
--         "motivo_revisao": "publicacao_inicial"
--       }
--     ]
--   }
--
--   Variante de COMPOSIÇÃO — mesmo formato; muda tipo e diretório:
--     "tipo_documento": "caderno_encargos",
--     "vigente": { ...,
--       "html_path":   "/composicoes/105006_2024-10_rev001.html",
--       "pdf_path":    "/composicoes/105006_2024-10_rev001.pdf",
--       "assets_path": "/composicoes/105006_2024-10_rev001_assets/" }
--
--   Regra de revisão: ao entrar nova revisão, ela vira "vigente"; a
--   anterior recebe edicao_fim e status != 'VIGENTE'; "revisoes"
--   preserva o histórico.
--
-- AUDITORIA (JSONB) — schema audit
--   audit.logs.log_dados_antes / log_dados_depois: snapshot do registro
--     afetado como objeto SIMPLES coluna→valor — NÃO embrulhar em
--     schema/tabela/pk (log_schema, log_tabela, log_registro_id e log_acao
--     já são colunas próprias). Cadastros: objeto completo; alta
--     frequência: diff parcial (só campos alterados).
--     Ex.: { "ins_descricao": "...", "ins_unidade": "UN", "ins_ti_id": 4 }
--   audit.api_logs.log_corpo_req: corpo da requisição (POST/PUT/PATCH/DELETE).
--     O conteúdo deve ser SANITIZADO antes da gravação. É VEDADO registrar
--     senha, token, segredo, chave privada, credenciais ou dados sensíveis.
--     Alteração estrutural deste JSONB = mudança de contrato interno da app.
--     Ex.: { "codigo": "45087", "descricao": "..." }
--   audit.login_logs.log_detalhes: metadados do evento de autenticação.
--     Ex.: { "motivo_falha": "senha_invalida", "tentativas": 3 }
--          | { "provider_sub": "...", "scopes": [...] }
--
--   Os JSONB de catalogo.insumos_historico e catalogo.composicoes_historico
--   têm ESTRUTURA RECOMENDADA (não contrato rígido) no comentário de cada tabela.
-- ============================================================


