        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_aid_ati_drv
        UNIQUE (aid_ati_id, aid_drv_id),
    CONSTRAINT ck_aid_meta_obj
        CHECK (aid_meta_json IS NULL OR jsonb_typeof(aid_meta_json) = 'object')
);

CREATE INDEX ix_aid_ati
