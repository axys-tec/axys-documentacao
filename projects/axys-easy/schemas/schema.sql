-- TABELA: ativo.memo_calc / memo_calc_item       (contrato §8.10)
-- Memória de cálculo. DUAS origens, MESMO schema (consistência — decisão Renan 2026-06-14):
--   • PLUGIN/API (CAD/RVT/IFC): VERDADE = mc_json_cru (payload bruto); itens parseados.
--   • MANUAL (usuário digita): mc_json_cru NULL; VERDADE = os memo_calc_item digitados.
-- Um registro por import/lançamento; um filho por bloco/coletor/linha. SEM tabela de
-- entidades nem overlays relacionais (overlay é DERIVADO no viewer).
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.memo_calc (
    mc_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mc_atv_id           INTEGER NOT NULL,
    mc_origem           TEXT    NOT NULL,                  -- VIA PLUGIN/API: 'CAD'|'RVT'|'IFC' | DIGITADA: 'MANUAL'. platform fica no json_cru (axysCAD §1.2)
    mc_arquivo          TEXT,                              -- source.file_name (plugin); NULL no MANUAL
    mc_hash             TEXT,                              -- checksum p/ provenance (plugin); NULL no MANUAL
    mc_json_cru         JSONB,                             -- payload axys-cad-v1 bruto = verdade (plugin). NULL no MANUAL (verdade = os memo_calc_item digitados)
    mc_importado_em     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mc_importado_por    TEXT,

    CONSTRAINT fk_mc_atv
        FOREIGN KEY (mc_atv_id)
        REFERENCES ativo.ativos (atv_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_mc_origem
        CHECK (mc_origem IN ('CAD', 'RVT', 'IFC', 'MANUAL')),
    CONSTRAINT ck_mc_json_obj
        CHECK (mc_json_cru IS NULL OR jsonb_typeof(mc_json_cru) = 'object'),
    -- plugin/API SEMPRE traz o payload bruto; MANUAL não tem payload (digitação é a verdade)
    CONSTRAINT ck_mc_json_por_origem
        CHECK (mc_origem = 'MANUAL' OR mc_json_cru IS NOT NULL),
    -- UPSERT idempotente por arquivo (axysCAD §9: reenviar o mesmo arquivo sobrescreve).
    -- MANUAL tem mc_arquivo NULL → NULLs não colidem (vários memos manuais por ativo OK).
    CONSTRAINT uq_mc_atv_arquivo
        UNIQUE (mc_atv_id, mc_arquivo)
);

