-- TABELA: catalogo.edicoes
-- Contrato funcional (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_EDICOES.md
-- Cada publicação de uma fonte de preços.
--
-- edi_mes_ref:       1º dia do mês de referência (DATE).
-- edi_codigo_versao: rótulo da edição.
--   Fonte VERSAO (CDHU) → nº do boletim ('184'..'201'); usado também p/ ordenar.
--   Fonte DATA (SINAPI) → rótulo MM-YY do boletim mensal ('08-24'); ordena por edi_mes_ref.
-- edi_uf_padrao:     UF exibida por padrão na consulta.
--   SINAPI: 'SP' — todas 27 UFs estão importadas na edição.
--   CDHU:   'SP' — fonte estadual, apenas SP.
--   FDE:    'SP' — fonte estadual, apenas SP.
-- edi_situacao_ciclo: estado único da edição (BUSINESS_RULES §10) — substitui o antigo
--   par ciclo+edi_ativa (que se sobrepunham). Enum:
--     'RASCUNHO'   = em construção/import; indisponível (nada usa ainda); editável.
--     'PUBLICADA'  = liberada (gates ok); disponível p/ uso novo E histórico; TRAVADA/imutável.
--     'EM_REVISAO' = só pós-PUBLICADA, se houver recall/correção: edição REABERTA (mutável p/
--                    o staff aplicar a correção), mas SEGUE disponível ao tenant como a PUBLICADA,
--                    com AVISO de revisão (e o que será revisado, em edi_revisao_nota). Concluída,
--                    volta a 'PUBLICADA'.
--     'ARQUIVADA'  = descontinuada p/ NOVOS usos; histórico e usos existentes permanecem;
--                    imutável (raro). NÃO é "indisponível" — só não inicia coisas novas.
--   "Disponível para novo uso" := edi_situacao_ciclo IN ('PUBLICADA','EM_REVISAO').
--   "Acessível (histórico)"     := edi_situacao_ciclo IN ('PUBLICADA','EM_REVISAO','ARQUIVADA').
--   Travadas (imutáveis): 'PUBLICADA' e 'ARQUIVADA'. Mutáveis: 'RASCUNHO' e 'EM_REVISAO'.
--   Botão "Publicar" valida os gates abaixo (RASCUNHO→PUBLICADA). Lock na camada app, sem trigger.
-- edi_revisao_nota: texto opcional exibido ao tenant quando 'EM_REVISAO' (o que será revisado).
-- edi_ins_catalogo_ok / edi_comp_catalogo_ok: gates de upload de catálogo de DOCS (R2)
--   p/ poder publicar — fichas de insumo (auto-TRUE se fte_tem_catalogo_insumos=false) e
--   cadernos/critérios (obrigatório). Ver BUSINESS_RULES §10/§11.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.edicoes (
    edi_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edi_fte_id         INTEGER NOT NULL,
    edi_mes_ref        DATE    NOT NULL,
    edi_codigo_versao  TEXT,
    edi_uf_padrao      CHAR(2) NOT NULL DEFAULT 'SP',
    -- Estado único do ciclo de vida (BUSINESS_RULES §10) — ver comentário acima.
    -- RASCUNHO (default) → PUBLICADA → EM_REVISAO ⇄ PUBLICADA · ARQUIVADA (raro).
    -- NÃO há mais edi_ativa (sobreposição removida).
    edi_situacao_ciclo  TEXT    NOT NULL DEFAULT 'RASCUNHO',
    edi_revisao_nota    TEXT,   -- o que será revisado (exibido ao tenant quando EM_REVISAO)
    edi_ins_catalogo_ok  BOOLEAN NOT NULL DEFAULT FALSE,  -- fichas de insumo no R2 (auto-TRUE se fonte sem catálogo de insumos)
    edi_comp_catalogo_ok BOOLEAN NOT NULL DEFAULT FALSE,  -- cadernos/critérios no R2 (obrigatório p/ publicar)
    -- Resolução de documentos da edição (preenchido pelo IMPORT): por tipo de doc, o estado
    --   'ok' (doc vigente obtido) | 'indisponivel' (declarado no form OU não obtido — link morto).
    --   Tipos: metodologia, calculos, notas, cadernos, fichas. "Disponível para publicação" :=
    --   dados importados E todo tipo EXIGIDO pela fonte resolvido (ok|indisponivel). Publicar
    --   avisa+permite quando há 'indisponivel'. Ver CONTRATO IMPORT §8 / BUSINESS_RULES §10.
    edi_docs_status      JSONB,
    -- Pipeline de IMPORT desmembrado em 4 estágios (Preparar→Preços→Dados→Documentos). NÃO confundir
    -- com edi_docs_status (resolução de docs por tipo, acima). Shape por estágio:
    --   { "<nome>": { "estado": <e>, "job_id": <str?>, "em": <iso8601?>, "detalhe": <obj?> } }
    --   nomes: preparar | precos | dados | documentos (nesta ordem).
    --   estados: locked (travado) | pronto (destravado, pode rodar) | rodando | ok | erro |
    --            pendente_user (só 'precos' — modal Informar dado / Publicar sem preço).
    --   Cascata: estágio N vira locked→pronto quando N-1 == ok; 'documentos'==ok → edição disponível
    --   p/ publicar. Ver CONTRATO catalogo/IMPORT_ESTAGIOS.md. NULL = ainda não iniciado (default no back).
    edi_estagios         JSONB,
    -- edi_capa_path: apresentação dos cadernos SINAPI por subgrupo (capa+histórico+
    -- normas+bibliografia → HTML no R2). JSONB {subgrupo_slug: {url, path, ...}}.
    -- A edição é dona da apresentação (não há composição-capa); ver BUSINESS_RULES §11.
    edi_capa_path        JSONB,
    edi_criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edi_atualizado_em  TIMESTAMPTZ,
    edi_criado_por     TEXT,
    edi_atualizado_por TEXT,

    CONSTRAINT fk_edicoes_fte
        FOREIGN KEY (edi_fte_id)
        REFERENCES catalogo.fontes (fte_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT uq_edicoes_fte_mes
        UNIQUE (edi_fte_id, edi_mes_ref),

    CONSTRAINT ck_edicoes_primeiro_do_mes
        CHECK (EXTRACT(DAY FROM edi_mes_ref) = 1),

    CONSTRAINT ck_edicoes_codigo_versao_vazio
        CHECK (edi_codigo_versao IS NULL OR btrim(edi_codigo_versao) <> ''),

    CONSTRAINT ck_edicoes_situacao_ciclo
        CHECK (edi_situacao_ciclo IN ('RASCUNHO', 'PUBLICADA', 'EM_REVISAO', 'ARQUIVADA'))
);

CREATE INDEX ix_edicoes_fte_mes
    ON catalogo.edicoes (edi_fte_id, edi_mes_ref DESC);

