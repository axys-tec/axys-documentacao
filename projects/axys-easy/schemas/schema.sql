-- ============================================================
-- TABELA: catalogo.edicoes_leis_sociais
-- Contrato de regra de negócio (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_BUSINESS_RULES.md  (§3.3 Leis sociais)
