-- ============================================================
-- §ARQUIVAMENTO — desconstrução / reconstrução por tenant  [VALIDAR / pode virar contrato]
-- Problema: dados de orçamento de tenant SEM licença ativa há muito tempo não
-- podem ficar no banco quente (barato p/ 1, inviável p/ 10M). Evolui o backup R2 já
-- aprovado (memória project_audit_r2_backup) p/ ciclo por-tenant dirigido pelo Hub.
--
-- FRONTEIRA (X.2, decisão Renan): a REGRA/CONTEXTO/limites são do HUB. O Easy NÃO
-- conhece a regra — apenas EXECUTA quando chamado: (a) desconstruir(tenant) e
-- (b) reconstruir(tenant). O Hub documenta o ciclo do lado dele.
--
-- CICLO (serviço + Celery, não SQL puro):
--   1. DESCONSTRUÇÃO: Hub detecta tenant sem licença há > N dias (N em tabela do HUB)
--      → chama Easy → Celery async: SELECT de TODAS as tabelas do tenant (alcançáveis
--      via tenant_uuid nas raízes + FK) → BACKFILL JSON estruturado (mesmos nomes/roles
--      do banco) → grava no destino (R2 catalogado, ou schema frio) → DELETE do quente.
--   2. RECONSTRUÇÃO: Hub cobra e chama → Easy recarrega o backfill no quente.
--      PKs GENERATED BY DEFAULT permitem reinsert com id original (FKs preservadas).
--   3. RETENÇÃO: payloads guardados ~5 anos; não voltou, purga até de lá (gatilho do Hub).
--
-- POR QUE O SCHEMA JÁ SUPORTA: tenant_uuid só nas raízes + folhas por FK ⇒ recorte
-- por tenant é determinístico (sem rastrear tenant em toda folha). catalogo.* é GLOBAL
-- (nunca entra no backfill do tenant). Só falta o REGISTRO abaixo (o "catálogo no SQL").
--
-- arquivo.arquivamentos: registro de cada arquivamento (onde está, status, validade).
-- O payload em si vai p/ R2 (ou schema frio); aqui fica só o índice consultável.
-- ============================================================
CREATE SCHEMA IF NOT EXISTS arquivo;

GRANT USAGE ON SCHEMA arquivo TO "axys_tec";
ALTER DEFAULT PRIVILEGES IN SCHEMA arquivo
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "axys_tec";
ALTER DEFAULT PRIVILEGES IN SCHEMA arquivo
    GRANT USAGE, SELECT ON SEQUENCES TO "axys_tec";

CREATE TABLE IF NOT EXISTS arquivo.arquivamentos (
    arq_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arq_tenant_uuid     UUID    NOT NULL,                  -- tenant arquivado
    arq_status          TEXT    NOT NULL DEFAULT 'ARQUIVADO', -- ARQUIVADO | RESTAURADO | PURGADO
    arq_destino         TEXT    NOT NULL DEFAULT 'R2',      -- 'R2' | 'SCHEMA_FRIO'
    arq_localizacao     TEXT,                              -- path no R2 (ou nome do schema frio)
    arq_payload_hash    TEXT,                              -- checksum do backfill p/ integridade
    arq_tabelas_json    JSONB,                             -- { "ativo.ativos": 12, "ativo.ativo_itens": 3480, … } banco vs qtd
    arq_arquivado_em    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    arq_arquivado_por   TEXT,                              -- ator (serviço/hub)
    arq_restaurado_em   TIMESTAMPTZ,
    arq_expira_em       TIMESTAMPTZ,                       -- arquivado_em + 5 anos (purga)
    arq_meta_json       JSONB,

    CONSTRAINT ck_arq_status
        CHECK (arq_status IN ('ARQUIVADO', 'RESTAURADO', 'PURGADO')),
    CONSTRAINT ck_arq_destino
        CHECK (arq_destino IN ('R2', 'SCHEMA_FRIO')),
    CONSTRAINT ck_arq_tabelas_obj
        CHECK (arq_tabelas_json IS NULL OR jsonb_typeof(arq_tabelas_json) = 'object'),
    CONSTRAINT ck_arq_meta_obj
        CHECK (arq_meta_json IS NULL OR jsonb_typeof(arq_meta_json) = 'object')
);

CREATE INDEX ix_arq_tenant
    ON arquivo.arquivamentos (arq_tenant_uuid, arq_status);
CREATE INDEX ix_arq_expira
    ON arquivo.arquivamentos (arq_expira_em)
    WHERE arq_status = 'ARQUIVADO';