-- cc_custo_calculado: valor recalculado pela aplicação a partir dos
--   itens e preços disponíveis. NÃO substitui automaticamente o oficial.
-- cc_diferenca_valor: cc_custo_calculado - cc_custo_fonte (pode ser < 0).
-- cc_diferenca_percentual: cc_diferenca_valor / cc_custo_fonte quando
--   cc_custo_fonte > 0; NULL quando fonte é NULL/0 (não forçar cálculo).
-- cc_status_conferencia: classificação fonte × cálculo (ver CHECK).
-- cc_observacao_conferencia: nota livre da conferência.
-- A UI pode exibir ambos e destacar a diferença; NÃO mascarar divergência
--   nem gravar custo parcial como oficial. (Motor/trigger: não aqui.)
--
-- A EDIÇÃO vem de composicoes.cmp_edi_id via cc_cmp_id (composição é
--   versionada por edição) — sem coluna própria. Consultas por edição
--   fazem join com composicoes.
--
