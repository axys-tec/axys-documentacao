-- TABELA: catalogo.insumos_tipo
-- Contrato de regra de negócio (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_BUSINESS_RULES.md
-- Grupos de insumos para histogramas e relatórios.
-- Domínio estrutural — seed inline logo abaixo (todos os seeds vivem no schema).
--
-- NC = "Não Classificado": fallback técnico CONTROLADO de curadoria, NÃO é
--   categoria técnica real da fonte. Existe p/ permitir import completo sem
--   abortar (ins_ti_id é NOT NULL). Entra em fila de curadoria e NÃO deve
--   alimentar histogramas gerenciais como tipo técnico normal.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.insumos_tipo (
    ti_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ti_codigo          TEXT    NOT NULL,   -- MO|ENC_COMP|EQUIP_AQ|EQUIP_LOC|MAT|SERV|ESP|NC
    ti_nome            TEXT    NOT NULL,
    ti_ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    ti_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ti_atualizado_em   TIMESTAMPTZ,
    ti_criado_por      TEXT,
    ti_atualizado_por  TEXT,

    CONSTRAINT uq_insumos_tipo_codigo
        UNIQUE (ti_codigo),

    CONSTRAINT ck_insumos_tipo_codigo_vazio
        CHECK (btrim(ti_codigo) <> ''),

    CONSTRAINT ck_insumos_tipo_nome_vazio
        CHECK (btrim(ti_nome) <> '')
);

-- Seed estrutural — inline (NÃO há seed.sql separado: todos os seeds vivem
-- aqui no schema, aplicados pelo rebuild logo após o DDL).
