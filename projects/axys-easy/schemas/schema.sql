-- ============================================================
-- TABELA: catalogo.fontes
-- Contrato funcional (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_FONTES.md
-- Catálogo das fontes de preços (SINAPI, CDHU, AXYS). A importação de outras
-- fontes será doutrinada via template (fora do escopo atual).
--
-- fte_ordem_edicao:
--   'DATA'   — edição mais recente = maior edi_mes_ref
--   'VERSAO' — edição mais recente = maior edi_codigo_versao
-- fte_tem_catalogo_insumos: publica fichas de insumo? (só SINAPI). Se TRUE, a edição
--   exige upload das fichas p/ publicar (BUSINESS_RULES §10).
-- fte_catalogos_continuos: docs (fichas/cadernos/critérios) contínuos — não mudam por
--   edição? SINAPI=TRUE (skip por data de atualização); CDHU=FALSE (reemite por edição);
--   AXYS=TRUE (app-own). Ver BUSINESS_RULES §11.
--
-- Fonte 'AXYS': composições próprias do tenant — sem edição
--   mensal; preço informado direto, sem linha em insumos_preco.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.fontes (
    fte_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fte_codigo         TEXT    NOT NULL,   -- 'SINAPI' | 'CDHU' | 'AXYS'
    fte_nome           TEXT    NOT NULL,
    fte_ordem_edicao   TEXT    NOT NULL DEFAULT 'DATA',
    fte_ativa          BOOLEAN NOT NULL DEFAULT TRUE,
    -- Governança de catálogo de documentos (R2) — ver BUSINESS_RULES §10/§11:
    fte_tem_catalogo_insumos BOOLEAN NOT NULL DEFAULT FALSE,  -- publica fichas de insumo? (só SINAPI). Se TRUE, edição exige upload das fichas p/ publicar.
    fte_tem_caderno_metodologia BOOLEAN NOT NULL DEFAULT FALSE, -- publica livro/caderno de metodologia (conceitos, instruções)? SINAPI=TRUE; CDHU=TRUE; AXYS=FALSE.
    fte_catalogos_continuos  BOOLEAN NOT NULL DEFAULT FALSE,  -- docs contínuos (não mudam por edição → skip por data)? SINAPI=TRUE; CDHU=FALSE (reemite por edição).
    -- Segurança/governança (ver BUSINESS_RULES §8.1): permite criar/editar insumos,
    -- composições e ajustes manuais NESTA fonte? Só fontes PRÓPRIAS (AXYS) = TRUE.
    -- Catálogos de terceiros (SINAPI/CDHU) = FALSE → imutáveis por qualquer usuário
    -- (risco alto). Esta flag é o GATE consumido pelas telas de insumos/composições.
    fte_permite_manipular_dados BOOLEAN NOT NULL DEFAULT FALSE,
    -- EXIBIÇÃO dos arquivos originais no caderno técnico da edição (seção "Arquivos originais",
    -- entre Dados e Encargos Sociais). É SÓ flag de VITRINE — NÃO define bucket público nem
    -- libera o blob: o armazenamento (public/private) é decidido no import, independente disto.
    -- TRUE só p/ fontes cujos originais são de divulgação: AXYS (própria) e SINAPI (público oficial).
    fte_public         BOOLEAN NOT NULL DEFAULT FALSE,
    fte_criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fte_atualizado_em  TIMESTAMPTZ,
    fte_criado_por     TEXT,
    fte_atualizado_por TEXT,

    CONSTRAINT uq_fontes_codigo
        UNIQUE (fte_codigo),

    CONSTRAINT ck_fontes_codigo_vazio
        CHECK (btrim(fte_codigo) <> ''),

    CONSTRAINT ck_fontes_nome_vazio
        CHECK (btrim(fte_nome) <> ''),

    CONSTRAINT ck_fontes_ordem_edicao
        CHECK (fte_ordem_edicao IN ('DATA', 'VERSAO'))
);

CREATE INDEX ix_fontes_ativa
    ON catalogo.fontes (fte_ativa, fte_codigo);

-- Seed inline — fontes de preços do tenant.
-- IDs canônicos do catálogo base:
--   AXYS=1 · SINAPI=2 · CDHU=3 · FDE=4
--   fte_ordem_edicao: 'DATA' = mais recente é maior edi_mes_ref;
--                     'VERSAO' = mais recente é maior edi_codigo_versao.
--   fte_tem_catalogo_insumos: SINAPI publica fichas de insumo; CDHU/FDE/AXYS não.
--   fte_tem_caderno_metodologia: SINAPI, CDHU e FDE publicam cadernos/livros técnicos; AXYS não.
--   fte_catalogos_continuos:  SINAPI traz data de atualização (skip por data); CDHU/FDE reemitem
--                             por edição; AXYS é app-own (contínuo).
--   fte_permite_manipular_dados: SÓ AXYS (fonte própria) = TRUE; terceiros = FALSE (imutáveis).
INSERT INTO catalogo.fontes (fte_id, fte_codigo, fte_nome, fte_ordem_edicao,
