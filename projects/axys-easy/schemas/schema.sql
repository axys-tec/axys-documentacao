        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT uq_cc_cmp_uf_mod
        UNIQUE (cc_cmp_id, cc_uf, cc_modalidade),

    CONSTRAINT ck_cc_modalidade
