    ins_tenant_uuid     UUID    NOT NULL,                  -- RAIZ de isolamento. [VALIDAR] sem FK física.
    ins_codigo          TEXT    NOT NULL,
    ins_descricao       TEXT    NOT NULL,
    ins_unidade         TEXT    NOT NULL,
    ins_ti_id           INTEGER NOT NULL,                  -- classificação (MO/MAT/EQUIP…) — FK ao lookup GLOBAL
