-- ============================================================
-- TABELA: catalogo.conversao_mo_fte_to_sinapi   (2026-06-16)
-- Normaliza MÃO DE OBRA de outras fontes para a MO-SINAPI, p/ o orçamento falar
-- UMA língua de MO (não misturar servente CDHU c/ servente SINAPI no mesmo orçamento).
--
-- ASSIMETRIA: o lado ORIGEM é um INSUMO-MO da fonte (ex.: CDHU B.01.000.010146,
-- Servente, H — folha simples); o lado ALVO é uma COMPOSIÇÃO-MO da SINAPI (ex.:
-- 88316, SERVENTE COM ENCARGOS COMPLEMENTARES — que explode em EPI/ferramenta/curso/
-- salário). Por isso cmf_sinapi_cmp_id é COMPOSIÇÃO, não insumo.
--
-- AS-OF edição: o equivalente pode mudar quando a fonte ou a SINAPI rotaciona.
--
-- ENCADEIA com composicoes_mapeamento_mdo (NÃO precisa de de-para mensalista próprio
-- da fonte): pipeline de resolução = 1º normaliza FONTE (aqui, vira SINAPI-horista),
-- 2º normaliza REGIME (mapeamento_mdo horista→mensalista × cmm_fator_unidade).
-- Ordem fixa: fonte antes de regime (o de-para mensalista só conhece códigos SINAPI).
--
-- CURADORIA (check periódico, não runtime): todo cmf_sinapi_cmp_id deve existir como
-- cmm_cmp_id_h em composicoes_mapeamento_mdo (na mesma edição), senão o passo de
-- regime mensalista não acha o swap.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.conversao_mo_fte_to_sinapi (
    cmf_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cmf_edi_id          INTEGER NOT NULL,                  -- AS-OF edição (FK catalogo.edicoes)
    cmf_fte_origem      TEXT    NOT NULL,                  -- 'CDHU' | (futuras fontes) — discriminador de fonte
    cmf_origem_ins_id   BIGINT  NOT NULL,                  -- insumo-MO da fonte (folha). FK polimórfica via app (origem varia).
    cmf_sinapi_cmp_id   BIGINT  NOT NULL,                  -- COMPOSIÇÃO-MO SINAPI equivalente (alvo)
    cmf_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cmf_atualizado_em   TIMESTAMPTZ,
    cmf_criado_por      TEXT,
    cmf_atualizado_por  TEXT,

    CONSTRAINT fk_conversao_mo_fte_edi
        FOREIGN KEY (cmf_edi_id)
        REFERENCES catalogo.edicoes (edi_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- alvo é composição SINAPI (FK física garante integridade do lado SINAPI)
    CONSTRAINT fk_conversao_mo_fte_sinapi_cmp
        FOREIGN KEY (cmf_sinapi_cmp_id)
        REFERENCES catalogo.composicoes (cmp_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- origem é insumo de FONTE variável → sem FK física (resolvida pelo app via cmf_fte_origem)
    CONSTRAINT uq_conversao_mo_fte
        UNIQUE (cmf_edi_id, cmf_fte_origem, cmf_origem_ins_id)
);

CREATE INDEX ix_conversao_mo_fte_edi
    ON catalogo.conversao_mo_fte_to_sinapi (cmf_edi_id, cmf_fte_origem);
CREATE INDEX ix_conversao_mo_fte_sinapi
    ON catalogo.conversao_mo_fte_to_sinapi (cmf_sinapi_cmp_id);


