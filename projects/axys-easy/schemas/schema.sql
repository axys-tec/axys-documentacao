    ti_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ti_codigo          TEXT    NOT NULL,   -- MO|ENC_COMP|EQUIP_AQ|EQUIP_LOC|MAT|SERV|ESP|NC
