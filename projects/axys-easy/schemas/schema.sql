-- ============================================================
-- catalogo.unidades — VOCABULÁRIO CONTROLADO de unidades de grandeza.
-- Por que existe: import vem (quase) normalizado, mas a CRIAÇÃO MANUAL de
-- insumos/composições (fontes próprias, AXYS) geraria lixo/typos (m4, m5,
-- M2/MES × M2XMES...). Centraliza o vocabulário e dá integridade.
-- PK NATURAL = o próprio código (texto): o que fica gravado em
--   insumos.ins_unidade / composicoes.cmp_unidade é o código legível
--   ('M3','KG','UN','M3XKM') — NÃO um id surrogate (banco continua legível).
-- Contraste com situação: unidade é vocabulário grande/extensível → TABELA;
--   situação é enum pequeno/fixo → CHECK. (Princípio em BUSINESS_RULES §6/§8.2.)
-- Compostas existem (transporte/locação): M3XKM, TXKM, M2XMES → use TEXT
--   (não char(3/4)). Convenção canônica a fechar: maiúsculas, separador 'X'
--   p/ composta, sem acento ('MES') — normalizar variantes na Fase 2.
-- ALVO FASE 2 (NEXT_STEPS): FK ins_unidade/cmp_unidade → unidades(un_codigo);
--   import faz UPSERT (cria a unidade se não existir); criação MANUAL só
--   seleciona da lista (+ "Outra" = nova unidade, restrita a admin + confirmação).
-- Seed abaixo = núcleo canônico; o restante o import popula/normaliza.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.unidades (
    un_codigo        TEXT PRIMARY KEY,   -- código natural legível; é o valor gravado nas FKs (sem surrogate)
    un_descricao     TEXT,               -- rótulo amigável (ex.: 'Metro cúbico') — pode ser preenchido depois
    un_categoria     TEXT,               -- hook p/ conversão (comprimento|area|volume|massa|tempo|composta|outro) — ver §9.5
    un_ativo         BOOLEAN NOT NULL DEFAULT TRUE,
    un_criado_em     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    un_atualizado_em TIMESTAMPTZ,
    un_criado_por    TEXT,
    un_atualizado_por TEXT,

    CONSTRAINT ck_unidades_codigo_vazio CHECK (btrim(un_codigo) <> '')
);

