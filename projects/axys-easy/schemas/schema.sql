-- ============================================================
-- TABELA: catalogo.insumos_tipo
-- Contrato de regra de negócio (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_BUSINESS_RULES.md
-- Grupos de insumos para histogramas e relatórios.
-- Domínio estrutural — seed inline logo abaixo (todos os seeds vivem no schema).
--
-- NC = "Não Classificado": fallback técnico CONTROLADO de curadoria, NÃO é
--   categoria técnica real da fonte. Existe p/ permitir import completo sem
--   abortar (ins_ti_id é NOT NULL). Entra em fila de curadoria e NÃO deve
--   alimentar histogramas gerenciais como tipo técnico normal.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.insumos_tipo (
    ti_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ti_codigo          TEXT    NOT NULL,   -- MO|ENC_COMP|EQUIP_AQ|EQUIP_LOC|MAT|SERV|ESP|NC
    ti_nome            TEXT    NOT NULL,
    ti_ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    ti_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ti_atualizado_em   TIMESTAMPTZ,
    ti_criado_por      TEXT,
    ti_atualizado_por  TEXT,

    CONSTRAINT uq_insumos_tipo_codigo
        UNIQUE (ti_codigo),

    CONSTRAINT ck_insumos_tipo_codigo_vazio
        CHECK (btrim(ti_codigo) <> ''),

    CONSTRAINT ck_insumos_tipo_nome_vazio
        CHECK (btrim(ti_nome) <> '')
);

-- Seed estrutural — inline (NÃO há seed.sql separado: todos os seeds vivem
-- aqui no schema, aplicados pelo rebuild logo após o DDL).
INSERT INTO catalogo.insumos_tipo (ti_codigo, ti_nome, ti_criado_por)
SELECT v.codigo, v.nome, 'Axys — seed inicial'
FROM (VALUES
    ('MO',       'Mão de Obra'),
    ('ENC_COMP', 'Encargos Complementares'),
    ('EQUIP_AQ', 'Equipamento — Aquisição'),
    ('EQUIP_LOC','Equipamento — Locação'),
    ('MAT',      'Material'),
    ('SERV',     'Serviço'),
    ('ESP',      'Especiais'),
    ('NC',       'Não Classificado (fallback de curadoria)')
) AS v(codigo, nome)
ON CONFLICT (ti_codigo) DO NOTHING;


-- ============================================================
-- TABELA: catalogo.situacoes
-- Contrato de regra de negócio (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_BUSINESS_RULES.md
-- Domínio controlado de situações do catálogo (lookup por FK — substitui
-- texto repetido em massa). DOIS domínios apenas:
--   INSUMO     → situação do PREÇO do insumo naquela UF/edição (insumos_preco).
--   COMPOSICAO → situação declarada da composição.
-- Não há domínio 'PRECO' (situação de preço É do insumo) nem 'ITEM' (item é
-- só insumo ou composição dentro de composição).
-- A situação aqui é a DECLARADA pela fonte (auditoria). Coerência preço×
-- situação e o cálculo efetivo são contrato da APP — NÃO há trigger.
-- A FK composta (sit_id, dominio) garante DOMÍNIO válido no banco.
-- Domínio estrutural — seed inline logo abaixo (todos os seeds vivem no schema).
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.situacoes (
    sit_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sit_dominio   TEXT     NOT NULL,
    sit_codigo    TEXT     NOT NULL,
    sit_descricao TEXT     NOT NULL,
    sit_ordem     SMALLINT NOT NULL DEFAULT 0,
    sit_ativo     BOOLEAN  NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_situacoes_dominio
        CHECK (sit_dominio IN ('INSUMO', 'COMPOSICAO')),

    CONSTRAINT uq_situacoes_dominio_codigo
        UNIQUE (sit_dominio, sit_codigo),

    -- alvo das FKs compostas de domínio (garante domínio válido sem trigger):
    CONSTRAINT uq_situacoes_id_dominio
        UNIQUE (sit_id, sit_dominio)
);

-- Seed estrutural — inline (situacoes não tem colunas de auditoria).
INSERT INTO catalogo.situacoes (sit_dominio, sit_codigo, sit_descricao, sit_ordem) VALUES
    ('INSUMO',    'COM_PRECO', 'Preço publicado pela fonte na UF/edição', 1),
    ('INSUMO',    'SEM_PRECO', 'Insumo existe, fonte não publicou preço', 2),
    ('COMPOSICAO','COM_CUSTO', 'Composição com custo na edição',          1),
    ('COMPOSICAO','SEM_CUSTO', 'Composição sem custo (item faltante)',    2),
    ('COMPOSICAO','SUSPENSO',  'Composição suspensa',                     3),
    ('COMPOSICAO','EM_ESTUDO', 'Composição em estudo',                    4)
ON CONFLICT (sit_dominio, sit_codigo) DO NOTHING;


-- ============================================================
-- TABELA: catalogo.fontes
-- Contrato funcional (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_FONTES.md
-- Catálogo das fontes de preços (SINAPI, CDHU, AXYS). A importação de outras
-- fontes será doutrinada via template (fora do escopo atual).
--
-- fte_ordem_edicao:
--   'DATA'   — edição mais recente = maior edi_mes_ref
--   'VERSAO' — edição mais recente = maior edi_codigo_versao
--
-- Fonte 'AXYS': composições próprias do tenant — sem edição
--   mensal; preço informado direto, sem linha em insumos_preco.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.fontes (
    fte_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fte_codigo         TEXT    NOT NULL,   -- 'SINAPI' | 'CDHU' | 'AXYS'
    fte_nome           TEXT    NOT NULL,
    fte_ordem_edicao   TEXT    NOT NULL DEFAULT 'DATA',
    fte_ativa          BOOLEAN NOT NULL DEFAULT TRUE,
    -- Governança de catálogo de documentos (R2) — ver BUSINESS_RULES §10/§11:
    fte_tem_catalogo_insumos BOOLEAN NOT NULL DEFAULT FALSE,  -- publica fichas de insumo? (só SINAPI). Se TRUE, edição exige upload das fichas p/ publicar.
    fte_catalogos_continuos  BOOLEAN NOT NULL DEFAULT FALSE,  -- docs contínuos (não mudam por edição → skip por data)? SINAPI=TRUE; CDHU=FALSE (reemite por edição).
    fte_criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fte_atualizado_em  TIMESTAMPTZ,
    fte_criado_por     TEXT,
    fte_atualizado_por TEXT,

    CONSTRAINT uq_fontes_codigo
        UNIQUE (fte_codigo),

    CONSTRAINT ck_fontes_codigo_vazio
        CHECK (btrim(fte_codigo) <> ''),

    CONSTRAINT ck_fontes_nome_vazio
        CHECK (btrim(fte_nome) <> ''),

    CONSTRAINT ck_fontes_ordem_edicao
        CHECK (fte_ordem_edicao IN ('DATA', 'VERSAO'))
);

CREATE INDEX ix_fontes_ativa
    ON catalogo.fontes (fte_ativa, fte_codigo);

-- Seed inline — fontes de preços do tenant.
--   fte_ordem_edicao: 'DATA' = mais recente é maior edi_mes_ref;
--                     'VERSAO' = mais recente é maior edi_codigo_versao.
--   fte_tem_catalogo_insumos: SINAPI publica fichas de insumo; CDHU/AXYS não.
--   fte_catalogos_continuos:  SINAPI traz data de atualização (skip por data); CDHU reemite
--                             por edição; AXYS é app-own (contínuo).
INSERT INTO catalogo.fontes (fte_codigo, fte_nome, fte_ordem_edicao,
                             fte_tem_catalogo_insumos, fte_catalogos_continuos, fte_criado_por)
SELECT v.codigo, v.nome, v.ordem, v.tem_ins, v.continuos, 'Axys — seed inicial'
FROM (VALUES
    ('SINAPI', 'SINAPI — Caixa Econômica Federal',                          'DATA',   TRUE,  TRUE),
    ('CDHU',   'CDHU — Companhia de Desenvolvimento Habitacional e Urbano', 'VERSAO', FALSE, FALSE),
    ('AXYS',   'AXYS — Composições Próprias',                               'DATA',   FALSE, TRUE)
) AS v(codigo, nome, ordem, tem_ins, continuos)
ON CONFLICT (fte_codigo) DO UPDATE
    SET fte_nome           = EXCLUDED.fte_nome,
        fte_ordem_edicao   = EXCLUDED.fte_ordem_edicao,
        fte_tem_catalogo_insumos = EXCLUDED.fte_tem_catalogo_insumos,
        fte_catalogos_continuos  = EXCLUDED.fte_catalogos_continuos,
        fte_atualizado_em  = CURRENT_TIMESTAMP,
        fte_atualizado_por = 'Axys — seed inicial';


-- ============================================================
-- TABELA: catalogo.edicoes
-- Contrato funcional (canônico):
--   docs/projects/axys-easy/contracts/catalogo/CATALOGO_EDICOES.md
-- Cada publicação de uma fonte de preços.
--
-- edi_mes_ref:       1º dia do mês de referência (DATE).
-- edi_codigo_versao: rótulo da edição.
--   Fonte VERSAO (CDHU) → nº do boletim ('184'..'201'); usado também p/ ordenar.
--   Fonte DATA (SINAPI) → rótulo MM-YY do boletim mensal ('08-24'); ordena por edi_mes_ref.
-- edi_uf_padrao:     UF exibida por padrão na consulta.
--   SINAPI: 'SP' — todas 27 UFs estão importadas na edição.
--   CDHU:   'SP' — fonte estadual, apenas SP.
-- ============================================================
CREATE TABLE IF NOT EXISTS catalogo.edicoes (
    edi_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edi_fte_id         INTEGER NOT NULL,
    edi_mes_ref        DATE    NOT NULL,
    edi_codigo_versao  TEXT,
    edi_uf_padrao      CHAR(2) NOT NULL DEFAULT 'SP',
    edi_ativa          BOOLEAN NOT NULL DEFAULT TRUE,
    -- Ciclo de vida (BUSINESS_RULES §10): RASCUNHO = importada, indisponível ao tenant;
    -- PUBLICADA = liberada (validações ok) + TRAVADA (imutável; lock na camada app).
    edi_situacao_ciclo  TEXT    NOT NULL DEFAULT 'RASCUNHO',
    edi_ins_catalogo_ok  BOOLEAN NOT NULL DEFAULT FALSE,  -- fichas de insumo no R2 (auto-TRUE se fonte sem catálogo de insumos)
    edi_comp_catalogo_ok BOOLEAN NOT NULL DEFAULT FALSE,  -- cadernos/critérios no R2 (obrigatório p/ publicar)
    edi_criado_em      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edi_atualizado_em  TIMESTAMPTZ,
    edi_criado_por     TEXT,
    edi_atualizado_por TEXT,

    CONSTRAINT fk_edicoes_fte
        FOREIGN KEY (edi_fte_id)
        REFERENCES catalogo.fontes (fte_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT uq_edicoes_fte_mes
        UNIQUE (edi_fte_id, edi_mes_ref),

    CONSTRAINT ck_edicoes_primeiro_do_mes
        CHECK (EXTRACT(DAY FROM edi_mes_ref) = 1),

    CONSTRAINT ck_edicoes_codigo_versao_vazio
        CHECK (edi_codigo_versao IS NULL OR btrim(edi_codigo_versao) <> ''),

    CONSTRAINT ck_edicoes_situacao_ciclo
        CHECK (edi_situacao_ciclo IN ('RASCUNHO', 'PUBLICADA'))
);

CREATE INDEX ix_edicoes_fte_mes
    ON catalogo.edicoes (edi_fte_id, edi_mes_ref DESC);

CREATE INDEX ix_edicoes_ativas
    ON catalogo.edicoes (edi_fte_id, edi_ativa)
    WHERE edi_ativa = TRUE;

