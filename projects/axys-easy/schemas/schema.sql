-- ============================================================
-- ╔══════════════════════════════════════════════════════════════════════════╗
-- ║ ALVO FASE 2 — `situacoes` SAI (decisão Renan 2026-06-07). Ver §6 do      ║
-- ║ CATALOGO_BUSINESS_RULES. Situação vira CHECK-text, igual às composições:   ║
-- ║   insumos_preco: trocar (pri_sit_id, pri_sit_dominio + FK composta + CHECK)║
-- ║   por  pri_situacao TEXT CHECK (pri_situacao IS NULL OR IN ('COM PREÇO',    ║
-- ║   'SEM PREÇO')). null = sem preço/sem custo.                               ║
-- ║ Motivo: a lookup só era usada por insumos_preco (composições já usam       ║
-- ║ CHECK-text; as linhas COMPOSICAO daqui eram peso morto). Enum pequeno e    ║
-- ║ fixo → CHECK; não vale uma tabela. Mantida abaixo até o recreate (parser   ║
