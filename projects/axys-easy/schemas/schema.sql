-- TABELA: ativo.ativo_itens               (contrato §8.6)  ★ CORAÇÃO ★
-- Árvore canônica: parent_id + ordem ESPARSA + path. Numeração 1.2.3 é
-- RENDER, não dado. NÃO carrega tenant_uuid (deriva via ati_atv_id).
--
-- PREÇO NÃO É COLUNA AQUI. O item guarda o VÍNCULO (origem + cmp_id + qtd)
-- e a camada de AJUSTE reversível (ati_ajuste_json). Custo resolve ao vivo
-- contra a edição do contexto (orcamento_parametros). Sem ati_custo_base.
--
-- ati_cmp_origem: discriminador da FK polimórfica da composição.
--   CATALOGO → catalogo.composicoes | TENANT → tenant_catalogo.composicoes.
--   FK resolvida pelo app, NÃO pelo banco (polimórfica). NULL = linha estrutural
--   sem composição. (LOCAL removido 2026-06-16: alteração de composição espelha
--   direto para tenant_catalogo, não há mais fork de escopo-único.)
--
-- Vínculo item↔driver: NÃO é coluna aqui (evita zilhão de NULLs). É a tabela-ponte
--   ativo.ativo_itens_drivers (N:N) — só existe linha quando o item TEM driver.
--   Ver §CATÁLOGO DE ATIVOS / DRIVERS adiante.
-- ============================================================
CREATE TABLE IF NOT EXISTS ativo.ativo_itens (
    ati_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ati_atv_id          INTEGER NOT NULL,
    ati_parent_id       INTEGER,                           -- pai na árvore; NULL = raiz. PROFUNDIDADE vem daqui.
    ati_ordem           INTEGER NOT NULL,                  -- ordem ESPARSA entre irmãos (1000, 2000…)
    ati_path            TEXT    NOT NULL,                  -- "0001.0002.0001" — DERIVADO; p/ ORDER BY e descendência
    ati_tipo            TEXT    NOT NULL,                  -- GRUPO | SERVIÇO | SUBTOTAL | TEXTO | OBSERVAÇÃO…
    ati_descricao       TEXT,
    ati_cmp_origem      TEXT,                              -- 'CATALOGO' | 'TENANT' | NULL
    ati_cmp_id          INTEGER,                           -- id da composição NA origem (FK polimórfica via app)
    ati_quantidade      NUMERIC(18,6),                     -- derivada da memória se houver; senão digitada
    ati_unidade         TEXT,
    ati_bdi_id          INTEGER,                           -- BDI da linha (FK ativo_bdi; NULL em título/não-precificável). FK via ALTER (ver §BDI)
    ati_ajuste_json     JSONB,                             -- camada de ajuste REVERSÍVEL sobre o preço resolvido (§10)
    ati_have_memory_calc BOOLEAN NOT NULL DEFAULT FALSE,   -- qtd vem de memória (true) ou digitação (false)
    ati_regras_json     JSONB,                             -- metadados por tipo de linha
    ati_meta_json       JSONB,
    ati_criado_em       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ati_atualizado_em   TIMESTAMPTZ,
    ati_criado_por      TEXT,
    ati_atualizado_por  TEXT,

    CONSTRAINT fk_ati_atv
        FOREIGN KEY (ati_atv_id)
        REFERENCES ativo.ativos (atv_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ati_parent
        FOREIGN KEY (ati_parent_id)
        REFERENCES ativo.ativo_itens (ati_id)
        ON UPDATE CASCADE ON DELETE CASCADE,  -- deletar nó = deletar subárvore (primitiva "deletar")

    CONSTRAINT ck_ati_tipo
        CHECK (ati_tipo IN ('GRUPO', 'SERVIÇO', 'SUBTOTAL', 'TEXTO', 'OBSERVAÇÃO')),
    CONSTRAINT ck_ati_cmp_origem
        CHECK (ati_cmp_origem IS NULL OR ati_cmp_origem IN ('CATALOGO', 'TENANT')),
    -- coerência vínculo: origem e id andam juntos (ambos nulos ou ambos preenchidos)
    CONSTRAINT ck_ati_cmp_par
        CHECK ( (ati_cmp_origem IS NULL     AND ati_cmp_id IS NULL)
             OR (ati_cmp_origem IS NOT NULL AND ati_cmp_id IS NOT NULL) ),
    CONSTRAINT ck_ati_ajuste_obj
        CHECK (ati_ajuste_json IS NULL OR jsonb_typeof(ati_ajuste_json) = 'object'),
    -- não há dois irmãos com a mesma ordem sob o mesmo pai (no mesmo ativo)
    CONSTRAINT uq_ati_irmaos_ordem
