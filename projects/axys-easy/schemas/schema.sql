    ti_atualizado_em   TIMESTAMPTZ,
    ti_criado_por      TEXT,
    ti_atualizado_por  TEXT,

    CONSTRAINT uq_insumos_tipo_codigo
        UNIQUE (ti_codigo),

    CONSTRAINT ck_insumos_tipo_codigo_vazio
        CHECK (btrim(ti_codigo) <> ''),

    CONSTRAINT ck_insumos_tipo_nome_vazio
        CHECK (btrim(ti_nome) <> '')
);

