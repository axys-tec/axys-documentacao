-- TABELA: ativo.memo_calc / memo_calc_item       (contrato §8.10)
-- Memória de cálculo. DUAS origens, MESMO schema (consistência — decisão Renan 2026-06-14):
--   • PLUGIN/API (CAD/RVT/IFC): VERDADE = mc_json_cru (payload bruto); itens parseados.
--   • MANUAL (usuário digita): mc_json_cru NULL; VERDADE = o grid (mc_corpo) + os memo_calc_item.
-- Um registro por import/lançamento; um filho por bloco/coletor/linha. SEM tabela de
-- entidades nem overlays relacionais (overlay é DERIVADO no viewer).
--
-- GRID MANUAL — mc_corpo (decisão Renan 2026-06-26: EXPANSIBILIDADE via ID ESTÁVEL):
--   { "prox_id": <int monotônico, NUNCA reusa>,
--     "celulas": { "<cell_id>": { "l":linha, "c":coluna, "raw":"…", "b":?,"i":?,"u":? } } }
--   A IDENTIDADE da célula é o cell_id (imutável); a posição A–K×linha é DISPLAY (renumera
--   estilo Excel ao inserir/mover/excluir linha). Fórmulas e o vínculo ao item (mci_cell_id)
