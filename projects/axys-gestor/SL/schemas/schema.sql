-- ============================================================
-- Axys-Gestor / SL — Schema SQL
-- Banco: PostgreSQL 14+
-- Schemas: organization · catalog · planning · orders · purchases · tickets · royalties · audit
--
-- organization : cadastros organizacionais, parceiros, fornecedores, vínculos e segredos por loja.
-- catalog      : catálogo mestre de coleções, grupos, tipos, grades, produtos e anexos.
-- planning     : reservado para evolução futura de planejamento de coleção/compras.
-- orders       : pedidos comerciais por loja.
-- purchases    : compras / notas fiscais e seus itens.
-- tickets      : contestações, abatimentos e histórico operacional.
-- royalties    : consolidação e conciliação de royalties / marketing.
-- audit        : trilha de auditoria, login, API e políticas de retenção.
--
-- Decisões de arquitetura
-- ───────────────────────
-- NOMENCLATURA
--   Tabelas e colunas em inglês. Comentários, seeds e checks textuais em português-BR.
--   Mantém aderência ao ecossistema Axys e ao contrato interno da aplicação.
--
-- CHAVES / TENANCY
--   Tabelas transacionais usam BIGINT IDENTITY.
--   Entidades de cadastro usam INTEGER IDENTITY quando aplicável.
--   UUIDs de tenant/store/partner são gravados conforme contrato externo da app.
--
-- AUDITORIA
--   Onde aplicável: created_at, updated_at, created_by, updated_by.
--   Tabelas de anexos / histórico guardam apenas criação por serem eventos imutáveis.
--
-- VALORES / TIPOS
--   Timestamps: TIMESTAMPTZ; datas: DATE.
--   Valores monetários: NUMERIC(14,2).
--   JSONB estruturais são contrato interno da aplicação.
--
-- OBSERVAÇÃO
--   O schema planning é criado agora, mas suas tabelas ficam reservadas para evolução futura.
-- ============================================================

