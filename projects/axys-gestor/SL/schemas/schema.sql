    updated_at      TIMESTAMPTZ,
    created_by      TEXT,
    updated_by      TEXT,

    CONSTRAINT uq_brand_description
        UNIQUE (description),

    CONSTRAINT ck_brand_description_not_blank
        CHECK (btrim(description) <> '')
);


