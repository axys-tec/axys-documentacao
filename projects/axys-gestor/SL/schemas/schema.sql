CREATE TABLE IF NOT EXISTS orders."order" (
    order_id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_uuid                UUID NOT NULL,
    supplier_id               INTEGER NOT NULL,
    collection_id             INTEGER NOT NULL,
    order_number              TEXT NOT NULL,
    order_attachments_json    JSONB NOT NULL DEFAULT '[]'::jsonb,
    total_qty                 INTEGER NOT NULL DEFAULT 0,
    total_amount              NUMERIC(14,2) NOT NULL DEFAULT 0,
    status                    TEXT NOT NULL DEFAULT 'RASCUNHO',
    created_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMPTZ,
    created_by                TEXT,
    updated_by                TEXT,

    CONSTRAINT fk_order_supplier
        FOREIGN KEY (supplier_id) REFERENCES organization.supplier (supplier_id) ON DELETE RESTRICT,

    CONSTRAINT fk_order_collection
        FOREIGN KEY (collection_id) REFERENCES catalog.collection (collection_id) ON DELETE RESTRICT,

    CONSTRAINT uq_order_store_order_number
        UNIQUE (store_uuid, order_number),

    CONSTRAINT ck_order_number_not_blank
        CHECK (btrim(order_number) <> ''),

    CONSTRAINT ck_order_total_qty_non_negative
        CHECK (total_qty >= 0),

    CONSTRAINT ck_order_total_amount_non_negative
        CHECK (total_amount >= 0),

    CONSTRAINT ck_order_status
        CHECK (status IN ('RASCUNHO', 'APROVADO', 'FATURADO', 'CANCELADO'))
);


CREATE TABLE IF NOT EXISTS orders.order_product (
    order_product_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                 BIGINT NOT NULL,
    product_id               INTEGER NOT NULL,
    sell_in_unit_price       NUMERIC(14,2) NOT NULL DEFAULT 0,
    sell_in_total_amount     NUMERIC(14,2) NOT NULL DEFAULT 0,
    sell_out_unit_price      NUMERIC(14,2),
    sell_out_total_amount    NUMERIC(14,2),
    total_qty                INTEGER NOT NULL DEFAULT 0,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMPTZ,
    created_by               TEXT,
    updated_by               TEXT,

    CONSTRAINT fk_order_product_order
        FOREIGN KEY (order_id) REFERENCES orders."order" (order_id) ON DELETE CASCADE,

    CONSTRAINT fk_order_product_product
        FOREIGN KEY (product_id) REFERENCES catalog.product (product_id) ON DELETE RESTRICT,

    CONSTRAINT uq_order_product_order_product
        UNIQUE (order_id, product_id),

    CONSTRAINT ck_order_product_sell_in_unit_price_non_negative
        CHECK (sell_in_unit_price >= 0),

    CONSTRAINT ck_order_product_sell_in_total_amount_non_negative
        CHECK (sell_in_total_amount >= 0),

    CONSTRAINT ck_order_product_sell_out_unit_price_non_negative
        CHECK (sell_out_unit_price IS NULL OR sell_out_unit_price >= 0),

    CONSTRAINT ck_order_product_sell_out_total_amount_non_negative
        CHECK (sell_out_total_amount IS NULL OR sell_out_total_amount >= 0),

    CONSTRAINT ck_order_product_total_qty_non_negative
